// ---------------------------------------------------------------- breathing (per frame, from 131.36)
// control points in final-view px: head, beanie, shoulder, hand, forearm; sigma of each influence
const CPS = [[1200, 540, 140], [1390, 240, 150], [720, 380, 220], [1300, 665, 90], [1000, 790, 160]];
function breath(t) {
  if (t < LOCK) return CPS.map(() => [0, 0]);
  const k = Math.max(0, Math.min(BREATH.length - 1, Math.round((t - BREATH[0][0]) * 25)));
  const r = BREATH[k];
  const hand = [r[7], r[8]];
  return [[r[1], r[2]], [r[3], r[4]], [r[5], r[6]], hand, [hand[0] * 0.8, hand[1] * 0.8]];
}

// ---------------------------------------------------------------- key selection
// Orbit: the key nearest in time is drawn on top of the second nearest; they cross-fade over ~4 frames around the
// midpoint between keys. Locked: the fades follow the measured eye closure (133.00–133.44) and reopening
// (134.92–135.10); in between the nearest open/closed drawing is held.
function nearestTwo(t, times, span = 0.16) {
  const o = times.map((tk, i) => [Math.abs(t - tk), i]).sort((a, b) => a[0] - b[0]);
  const [d1, i1] = o[0], [d2, i2] = o[1];
  const sp = span > 0 ? span : Math.abs(times[i2] - times[i1]);        // span <= 0: fade over the whole gap
  return { top: i1, low: i2, a: Math.min(1, 0.5 + (d2 - d1) / sp) };
}
const FIG_T = FIG.map(([D]) => D.t);
const NORB = FIG.length - NLOCK;                       // orbit keys, then the locked ones (by time)
// locked keys: 131.44 132.6 (open) | 133.12 133.24 133.36 (closing) | 133.88 (shut) | 134.96 135.04 135.12 (opening) | 135.52
const SCHED = [[131.44, 0], [132.6, 1], [133.0, 1], [133.12, 2], [133.24, 3], [133.36, 4], [133.48, 5], [134.92, 5], [134.96, 6],
  [135.04, 7], [135.12, 8], [135.52, 9]].map(([t, k]) => [t, NORB + k]);
function figPair(t) {
  if (t < 131.44) return nearestTwo(t, FIG_T.slice(0, NORB + 1), t > 131.12 ? 0 : 0.16);   // the last gap fades throughout
  for (let i = 0; i < SCHED.length - 1; i++) {
    const [a, ka] = SCHED[i], [b, kb] = SCHED[i + 1];
    if (t <= b) {
      if (ka === kb) return { top: ka, low: ka, a: 1 };
      const u = (t - a) / (b - a);
      return u >= 0.5 ? { top: kb, low: ka, a: u } : { top: ka, low: kb, a: 1 - u };
    }
  }
  const k = SCHED[SCHED.length - 1][1];
  return { top: k, low: k, a: 1 };
}

// ---------------------------------------------------------------- the laptop lid (measured quad per frame)
function lidQuad(t) {
  const k = Math.max(0, Math.min(LIDQ.length - 1, Math.round((t - LIDQ[0][0]) * 25)));
  return LIDQ[k].slice(1);
}
const lerp2 = (a, b, u) => [a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u];
const dist = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
// lid colour field: a (cols+2) x (rows+2) canvas (edge cells repeated), one per frame, drawn with an affine map per triangle
let LIDC = null;
function lidColourCanvas(t) {
  const { cols, rows, orbit, lock } = LIDCOL;
  const k = t >= 131.42 ? -1 : Math.max(0, Math.min(orbit.length - 1, Math.round((t - orbit[0][0]) * 25)));
  if (!LIDC) LIDC = { c: canvas(cols + 2, rows + 2), k: null };
  if (LIDC.k !== k) {
    const g = LIDC.c.getContext("2d"), px = g.createImageData(cols + 2, rows + 2), src = k < 0 ? lock : orbit[k].slice(1);
    for (let y = 0; y < rows + 2; y++) for (let x = 0; x < cols + 2; x++) {
      const i = Math.max(0, Math.min(cols - 1, x - 1)), j = Math.max(0, Math.min(rows - 1, y - 1)), o = (y * (cols + 2) + x) * 4;
      px.data[o] = src[(j * cols + i) * 3]; px.data[o + 1] = src[(j * cols + i) * 3 + 1]; px.data[o + 2] = src[(j * cols + i) * 3 + 2]; px.data[o + 3] = 255;
    }
    g.putImageData(px, 0, 0);
    LIDC.k = k;
  }
  return LIDC.c;
}
function drawLidColour(ctx, P, t) {
  const { cols, rows } = LIDCOL, img = lidColourCanvas(t);
  // canvas x in [0, cols+2] -> u = 0.04 + 0.92 (x - 1) / cols ; y -> v = 0.05 + 0.90 (y - 1) / rows
  const a = 0.04 - 0.92 / cols, b = 0.92 / cols, c = 0.05 - 0.90 / rows, d = 0.90 / rows;
  const [TL, TR, BR, BL] = P;
  const tri = (O, U, V, su, sv, pts) => {
    // P = O + su*u*U + sv*v*V with u = a + bX, v = c + dY (su/sv = +-1 give the second triangle from BR)
    ctx.save(); ctx.beginPath(); ctx.moveTo(...pts[0]); ctx.lineTo(...pts[1]); ctx.lineTo(...pts[2]); ctx.closePath(); ctx.clip();
    const ux = U[0] - O[0], uy = U[1] - O[1], vx = V[0] - O[0], vy = V[1] - O[1];
    if (su > 0) ctx.transform(b * ux, b * uy, d * vx, d * vy, O[0] + a * ux + c * vx, O[1] + a * uy + c * vy);
    else ctx.transform(-b * ux, -b * uy, -d * vx, -d * vy, O[0] + (1 - a) * ux + (1 - c) * vx, O[1] + (1 - a) * uy + (1 - c) * vy);
    ctx.imageSmoothingEnabled = true; ctx.imageSmoothingQuality = "high";
    ctx.drawImage(img, 0, 0);
    ctx.restore();
  };
  // grow the clip triangles a little so their shared diagonal leaves no seam
  const grow = (pts) => { const cx = (pts[0][0] + pts[1][0] + pts[2][0]) / 3, cy = (pts[0][1] + pts[1][1] + pts[2][1]) / 3;
    return pts.map(([x, y]) => { const l = Math.hypot(x - cx, y - cy) || 1; return [x + (x - cx) / l * 3, y + (y - cy) / l * 3]; }); };
  tri(TL, TR, BL, 1, 1, grow([TL, TR, BL]));
  tri(BR, BL, TR, -1, -1, grow([BR, BL, TR]));
}
// the lid side strip's width (px) beyond the face's left keyline, measured
const SIDE = [[129.28, 12.3], [129.84, 12.0], [130.0, 8.8], [130.12, 7.6], [130.2, 5.8], [130.36, 3.2], [130.44, 0]];
// its colour between the two dark lines (pre-grade; measured band mean x1.2, the band's peak is brighter): pale grey early,
// darkening until it merges
const SIDEC = [[129.32, "#a09190"], [129.48, "#8b8280"], [129.64, "#857878"], [129.80, "#796b6c"], [130.0, "#5e5656"], [130.12, "#484040"], [130.2, "#231e22"]];
function sideColour(t) {
  if (t <= SIDEC[0][0]) return SIDEC[0][1];
  for (let i = 0; i < SIDEC.length - 1; i++) if (t < SIDEC[i + 1][0]) return mixHex(SIDEC[i][1], SIDEC[i + 1][1], (t - SIDEC[i][0]) / (SIDEC[i + 1][0] - SIDEC[i][0]));
  return SIDEC[SIDEC.length - 1][1];
}
function sideW(t) {
  if (t <= SIDE[0][0]) return SIDE[0][1];
  for (let i = 0; i < SIDE.length - 1; i++) if (t < SIDE[i + 1][0]) return SIDE[i][1] + (SIDE[i + 1][1] - SIDE[i][1]) * (t - SIDE[i][0]) / (SIDE[i + 1][0] - SIDE[i][0]);
  return 0;
}
function drawLid(ctx, t) {
  const q = lidQuad(t);
  const P = [[q[0], q[1]], [q[2], q[3]], [q[4], q[5]], [q[6], q[7]]];
  const r = 22 * dist(P[0], P[1]) / 740;
  const c = [(P[0][0] + P[1][0] + P[2][0] + P[3][0]) / 4, (P[0][1] + P[1][1] + P[2][1] + P[3][1]) / 4];
  const path = (g, inset, dx = 0, dy = 0) => {
    const [A, B, Cc, D] = P.map((p) => { const p2 = lerp2(p, c, inset / Math.max(1, dist(p, c))); return [p2[0] + dx, p2[1] + dy]; });
    const ra = r / dist(A, B), rd = r / dist(A, D), rb = r / dist(B, Cc);
    g.beginPath();
    g.moveTo(...lerp2(A, B, ra));
    g.lineTo(...lerp2(B, A, ra));
    g.quadraticCurveTo(B[0], B[1], ...lerp2(B, Cc, rb));
    g.lineTo(Cc[0], Cc[1]);
    g.lineTo(D[0], D[1]);
    g.lineTo(...lerp2(A, D, rd));
    g.quadraticCurveTo(A[0], A[1], ...lerp2(A, B, ra));
    g.closePath();
  };
  ctx.save();
  // the lid's side (its thickness) shows as a pale strip beyond its left edge while the camera is round to the right:
  // measured outer-line offset from the face's left keyline (px, along the edge normal), 12 px early, gone by 130.44
  const w = sideW(t);
  if (w > 0.5) {
    const ex = P[0][0] - P[3][0], ey = P[0][1] - P[3][1], el = Math.hypot(ex, ey) || 1;   // BL -> TL
    const nx = ey / el, ny = -ex / el;                                                      // outward (left) normal
    path(ctx, 0, nx * w, ny * w);
    ctx.fillStyle = sideColour(t); ctx.fill(); ctx.lineWidth = 2.5; ctx.strokeStyle = "#1f1716"; ctx.stroke();
  }
  // the face: its measured colour field (per frame during the orbit, one median when locked), stretched smoothly over
  // the quad's two triangles
  ctx.save(); path(ctx, 0); ctx.clip();
  drawLidColour(ctx, P, t);
  // rim, measured across the top and right edges (pre-grade): outer keyline centred ~1 px inside the quad edge, a pale
  // bevel centred 5 px in, a dark inner line 9-10 px in. Early on the sun makes the top bevel bright and warm and the
  // keyline soft; the right edge has no bevel until ~130.8
  const R = rimColours(t);
  const seg = (inset, w, col, part) => {
    const [A, B, Cc] = P.map((p) => lerp2(p, c, inset / Math.max(1, dist(p, c))));
    ctx.beginPath();
    if (part === 0) { ctx.moveTo(...lerp2(A, B, 0.02)); ctx.lineTo(...lerp2(B, A, r / dist(A, B))); ctx.quadraticCurveTo(B[0], B[1], ...lerp2(B, Cc, r / dist(B, Cc))); }
    else { ctx.moveTo(...lerp2(B, Cc, r / dist(B, Cc))); ctx.lineTo(...lerp2(B, Cc, 0.97)); }
    ctx.lineWidth = w; ctx.strokeStyle = col; ctx.lineCap = "round"; ctx.stroke();
  };
  seg(5, 3.6, R.tb, 0); seg(9.5, 2.6, R.ti, 0);
  if (R.rb) { seg(5.5, 3.6, R.rb, 1); seg(10, 2.6, R.ri, 1); }
  ctx.restore();
  path(ctx, 0.8); ctx.lineWidth = 3.4; ctx.strokeStyle = R.tk; ctx.lineJoin = "round"; ctx.stroke();
  seg(0.8, 3.4, R.rk, 1);
  ctx.restore();
}
