const hex3 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const mixHex = (a, b, u) => { const A = hex3(a), B = hex3(b); return "rgb(" + A.map((v, i) => Math.round(v + (B[i] - v) * u)).join(",") + ")"; };
function rimColours(t) {
  let i = 0;
  while (i < RIM.length - 2 && t > RIM[i + 1][0]) i++;
  const a = RIM[i], b = RIM[i + 1], u = Math.max(0, Math.min(1, (t - a[0]) / (b[0] - a[0])));
  // the right bevel fades in between 130.40 and 130.80 (from the face's own tone, so null -> a transparent start)
  const rb = a[5] && b[5] ? mixHex(a[5], b[5], u) : b[5] ? `rgba(${hex3(b[5]).join(",")},${u.toFixed(3)})` : null;
  const ri = a[6] && b[6] ? mixHex(a[6], b[6], u) : b[6] ? `rgba(${hex3(b[6]).join(",")},${u.toFixed(3)})` : null;
  return { tk: mixHex(a[1], b[1], u), tb: mixHex(a[2], b[2], u), ti: mixHex(a[3], b[3], u), rk: mixHex(a[4], b[4], u), rb, ri };
}

// ---------------------------------------------------------------- key meshes and canvases (lazy)
// grid over the key's image, lifted to 3D with the key's camera and the measured depth of each vertex
function keyMesh(G, box, maxRatio = 99) {
  const cam = camAt(frameT(G.t));
  const { u0, v0, step, nu, nv, s } = G;
  const pos = new Float32Array(nu * nv * 3), uv = new Float32Array(nu * nv * 2), idx = [];
  const Rt = cam.R;
  for (let j = 0; j < nv; j++) for (let i = 0; i < nu; i++) {
    const k = j * nu + i, u = u0 + i * step, v = v0 + j * step, z = s[k];
    const dc = [(u - cam.cx) / cam.f * z, (v - cam.cy) / cam.f * z, z];
    // world = C + R^T dc
    pos.set([0, 1, 2].map((a) => cam.C[a] + Rt[0][a] * dc[0] + Rt[1][a] * dc[1] + Rt[2][a] * dc[2]), k * 3);
    uv.set([(u - box[0]) / box[2], (v - box[1]) / box[3]], k * 2);
  }
  // triangles; those spanning a depth jump (an object's edge against the wall behind) are left out, so the key
  // does not smear there and the other keys fill in
  // a depth jump shows as a spike in the second difference of disparity (1/z), which is ~0 on any plane
  const bad = new Uint8Array(nu * nv);
  const inv = (i, j) => 1 / s[Math.max(0, Math.min(nv - 1, j)) * nu + Math.max(0, Math.min(nu - 1, i))];
  for (let j = 0; j < nv; j++) for (let i = 0; i < nu; i++) {
    const c = inv(i, j);
    const lx = Math.abs(inv(i - 1, j) - 2 * c + inv(i + 1, j)), ly = Math.abs(inv(i, j - 1) - 2 * c + inv(i, j + 1));
    if (Math.max(lx, ly) > maxRatio) bad[j * nu + i] = 1;
  }
  const ok = (a, b, c) => !(bad[a] || bad[b] || bad[c]);
  for (let j = 0; j < nv - 1; j++) for (let i = 0; i < nu - 1; i++) {
    const k = j * nu + i;
    if (ok(k, k + 1, k + nu + 1)) idx.push(k, k + 1, k + nu + 1);
    if (ok(k, k + nu + 1, k + nu)) idx.push(k, k + nu + 1, k + nu);
  }
  return { pos, uv, idx: new Uint16Array(idx), nu, nv };
}
// ---------------------------------------------------------------- measured residuals of the re-projection (orbit)
// RESID[key][frame] holds, on every 2nd vertex of the key's grid, the screen-space offset between the 3D re-projection
// and the source's own motion (KLT tracks); upsampled here to every vertex. Missing entries (the key's own frame, or the
// locked view) mean no offset.
const RDEC = new Map();
function residOff(name, tf, mesh) {
  const E = RESID[name] && RESID[name][tf.toFixed(2)];
  if (!E) return null;
  const id = name + "@" + tf.toFixed(2);
  if (RDEC.has(id)) return RDEC.get(id);
  const [n2, m2, b64] = E;
  const bin = atob(b64), q = new Int8Array(bin.length);
  for (let i = 0; i < bin.length; i++) q[i] = (bin.charCodeAt(i) << 24) >> 24;
  const { nu, nv } = mesh, out = new Float32Array(nu * nv * 2), half = n2 * m2;
  for (let j = 0; j < nv; j++) for (let i = 0; i < nu; i++) {
    const x = Math.min(n2 - 1, i / 2), y = Math.min(m2 - 1, j / 2);
    const x0 = Math.floor(x), y0 = Math.floor(y), x1 = Math.min(n2 - 1, x0 + 1), y1 = Math.min(m2 - 1, y0 + 1), fx = x - x0, fy = y - y0;
    for (let c = 0; c < 2; c++) {
      const g = (xx, yy) => q[c * half + yy * n2 + xx];
      const v = (g(x0, y0) * (1 - fx) + g(x1, y0) * fx) * (1 - fy) + (g(x0, y1) * (1 - fx) + g(x1, y1) * fx) * fy;
      out[(j * nu + i) * 2 + c] = v * 0.5;
    }
  }
  if (RDEC.size > 24) RDEC.delete(RDEC.keys().next().value);
  RDEC.set(id, out);
  return out;
}
const figName = (K) => (K.t < 131.4 ? "fig" : "lock") + keyName(K.t);
