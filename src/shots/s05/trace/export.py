#!/usr/bin/env python3
# Write ../data/<layer>.js from the build (CACHE/layer_<name>.pkl). Encoding (decoded by ../ink.js):
#   numbers are packed like the "encoded polyline" format: each integer is zig-zag coded and written in 5-bit groups
#   (low group first, 0x20 = more follows), each group + 63 as one ASCII char.
#   rings  : per ring  n, x0, y0, dx1, dy1, ... (quarter px, relative to the layer box; deltas after the first point)
#   levels : [value (0..1000), ringsString] per iso level, nested: fill each even-odd over the previous
#   tone   : the same for the print texture's amplitude (0..1000 = 0..1 value), see tone.py
#   strokes: per stroke  value (0..1000) * 4 + caps (1 = the start tapers, 2 = the end tapers), n, x0, y0, w0, dx, dy, dw, ... (quarter px; width in 1/20 px)
import numpy as np, pickle, os, sys, json
import frames
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, '..', 'data')

def enc_int(n, out):
    n = int(n); z = (n << 1) ^ (n >> 63) if n < 0 else n << 1
    if n < 0: z = ((-n) << 1) - 1
    while z >= 0x20:
        out.append(chr((0x20 | (z & 0x1f)) + 63)); z >>= 5
    out.append(chr(z + 63))
def enc(nums):
    out = []
    for n in nums: enc_int(n, out)
    return ''.join(out)
def rings_str(rings):
    nums = []
    for r in rings:
        q = np.round(np.asarray(r, np.float64) * 4).astype(np.int64)
        nums.append(len(q)); nums += [q[0, 0], q[0, 1]]
        d = np.diff(q, axis=0)
        for dx, dy in d: nums += [dx, dy]
    return enc(nums)
def strokes_str(lay):
    nums = []; count = 0
    for pol in (-1, 1):       # dark lines first, the white lines over them
        for i, s in enumerate(lay['strokes'][pol]):
            if len(s) < 2: continue
            w = s[:, 2] * lay['wsc'][pol][i]
            q = np.round(s[:, :2] * 4).astype(np.int64); qw = np.round(w * 20).astype(np.int64)
            cp = lay['caps'][pol][i] if 'caps' in lay else (True, True)
            nums += [int(round(lay['vals'][pol][i] * 1000)) * 4 + (1 if cp[0] else 0) + (2 if cp[1] else 0), len(q), q[0, 0], q[0, 1], qw[0]]
            for k in range(1, len(q)): nums += [q[k, 0] - q[k - 1, 0], q[k, 1] - q[k - 1, 1], qw[k] - qw[k - 1]]
            count += 1
    return enc(nums), count

def export(name):
    lay = pickle.load(open(f'{frames.CACHE}/layer_{name}.pkl', 'rb'))
    x0, y0, x1, y1 = lay['box']
    st, n = strokes_str(lay)
    levels = [[int(round(v * 1000)), rings_str(r)] for v, r in lay['levels']]
    js = [f'// s05 ink layer "{name}": GENERATED by trace/export.py from the build in trace/ (see trace/README.md).',
          '// Vector data only: iso-value outlines of the value study and ink-stroke centre-lines with widths, measured on the',
          '// source frame; ../ink.js decodes and draws them. Do not edit by hand.',
          f'export const box = {json.dumps([x0, y0, x1, y1])};',
          f'export const base0 = {int(round(lay["base0"] * 1000))};',
          f'export const alpha = {json.dumps(rings_str(lay["alpha"]))};',
          'export const levels = [',
          *[f'  [{v}, {json.dumps(s)}],' for v, s in levels],
          '];',
          'export const tone = [',
          *[f'  [{int(round(v * 1000))}, {json.dumps(rings_str(r))}],' for v, r in lay.get('tone', [])],
          '];',
          f'export const strokes = {json.dumps(st)};',
          f'export const nStrokes = {n};', '']
    p = os.path.join(OUT, f'{name}.js'); open(p, 'w').write('\n'.join(js))
    print(name, n, 'strokes', len(levels), 'levels', os.path.getsize(p) // 1024, 'KB')

if __name__ == '__main__':
    for n in (sys.argv[1].split(',') if len(sys.argv) > 1 else ['room', 'desk', 'lh', 'rh', 'rhB', 'arm', 'armB', 'fig', 'owl', 'owlD']): export(n)
