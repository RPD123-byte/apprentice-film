#!/usr/bin/env python3
# Shot A owl traces (measurement script, not loaded by the film). Input: owlstack.npz = every source frame 1331-1381
# with the grade undone (grade.inverse on the full frame), registered on PATH_A (so the owl sits at its frame-1356
# placement) and cropped to X0,Y0 (360,60); D<n> = |frame - owl-free plate| (blurred 1.5) for the silhouettes.
#  - standing frames (1341-1381): the head/body/wing drawing is rigid per wing phase -> one trace per phase from the
#    per-phase median (level/up/down), inside the phase silhouette (consensus difference mask, closed, holes filled);
#  - feet: per frame, what the frame's own silhouette adds under the body (legs + feet change every frame);
#  - fly-in + landing (1331-1340, smeared): the whole owl traced per frame.
# Every trace = the silhouette (filled with the value of the owl's dark parts) + ink shapes at `levels`.
import sys, os, json, numpy as np, cv2
sys.path.insert(0, os.path.dirname(__file__))
from trace_plate import build, enc_ring
Z = np.load(sys.argv[1]); out = sys.argv[2]
X0, Y0 = 360, 60
LEV = [-1, 0.2, 0.45, 0.65, 0.8, 0.88, 0.94]   # dense near white: the owl's pencil shading lives in 0.7-1
cf = lambda f: f - (f - 1) // 25
ph = lambda f: ['level', 'up', 'level', 'down'][cf(f) % 4]
def fillholes(m):
    # holes = background not reachable from outside the image (pad by 1 px so the flood always starts outside)
    h, w = m.shape; ff = np.pad(m, 1); pad = np.zeros((h + 4, w + 4), np.uint8)
    cv2.floodFill(ff, pad, (0, 0), 255); return m | (~ff[1:-1, 1:-1] & 255)
def largest(m, keep=1, minA=0):
    n, lab, st, _ = cv2.connectedComponentsWithStats(m, 8)
    if n < 2: return m
    idx = [1 + i for i in np.argsort(-st[1:, 4])[:keep] if st[1 + i, 4] >= minA]
    return (np.isin(lab, idx) * 255).astype(np.uint8)
def silh(mm, thr, close=9, keep=1, minA=0):
    m = ((mm > thr) * 255).astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (close, close)))
    m = fillholes(m); m = largest(m, keep, minA)
    return cv2.morphologyEx(m, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5)))
def pack(P, mask, levels=LEV, eps=0.4):
    L = build(P, levels, eps=eps, bigA=300, mask=(mask > 0).astype(np.uint8), minarea=1.5)
    return [[[shift(v), [enc_ring(r + [X0, Y0]) for r in g]] for v, g in lay] for lay in L]
def shift(v):
    if isinstance(v, list): return [round(v[0] + X0, 1), round(v[1] + Y0, 1), v[2], round(v[3] + X0, 1), round(v[4] + Y0, 1), v[5]]
    return v
res = {'phase': {}, 'feet': {}, 'fly': {}}
sils = {}
for P in ['level', 'up', 'down']:
    fs = [f for f in range(1341, 1382) if ph(f) == P]
    mm = np.mean([Z[f'D{n}'] > 28 for n in fs], 0)
    med = np.median([Z[f'P{n}'] for n in fs], 0).astype(np.float32)
    s = silh(mm, 0.55); sils[P] = s
    res['phase'][P] = pack(med, s)
    print(P, 'ok', int((s > 0).sum()))
for n in range(1341, 1382):
    s = silh(Z[f'D{n}'] > 28, 0.5, keep=6, minA=40)
    body = cv2.dilate(sils[ph(n)], np.ones((3, 3), np.uint8))
    feet = s & ~body
    feet[:460 - Y0] = 0   # only under the belly (frame y > 460 at the 1356 placement)
    feet = largest(cv2.morphologyEx(feet, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8)), 4, 30)
    if feet.sum() == 0: continue
    Pn = cv2.GaussianBlur(Z[f'P{n}'], (0, 0), 0.6)
    res['feet'][n] = pack(Pn, feet, levels=[-1, 0.25, 0.5, 0.7, 0.85], eps=0.45)
for n in range(1331, 1341):   # the fly-in and the landing (still smeared, and 1339 is its own drawing)
    s = silh(Z[f'D{n}'] > 24, 0.5, close=15, keep=3, minA=200)
    Pn = cv2.GaussianBlur(Z[f'P{n}'], (0, 0), 0.8)
    res['fly'][n] = pack(Pn, s, levels=[-1, 0.25, 0.5, 0.7, 0.85, 0.93], eps=0.5)
with open(out, 'w') as f:
    f.write('// Generated by src/shots/s18/trace/trace_owlA.py — outline traces of the shot-A owl (frame px at its 1356\n')
    f.write('// placement): per wing phase (rigid head/body/wing), per-frame feet, per-frame smeared fly-in. See trace/README.md.\n')
    f.write('export const OWL_A_TRACE = '); json.dump(res, f, separators=(',', ':')); f.write(';\n')
print('wrote', out, os.path.getsize(out))
