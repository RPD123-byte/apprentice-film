const lin = (xs, vs, x) => {
  if (x <= xs[0]) return vs[0];
  for (let i = 1; i < xs.length; i++) if (x <= xs[i]) { const u = (x - xs[i - 1]) / (xs[i] - xs[i - 1]); return vs[i - 1] + (vs[i] - vs[i - 1]) * u; }
  return vs[vs.length - 1];
};
// the strip content, drawn in 24 px vertical slices each with its own measured offset
function drawStrip(g, T, alpha = 1) {
  const hc = sokoHeaderCanvas({ gaze: "down" }), F = HEADER_FRAMED;
  const w = warpAt(T);
  g.save();
  g.globalAlpha = alpha;
  if (!w) { g.drawImage(hc, F.x, F.y, F.w, F.h); g.restore(); return; }
  const DX = w.slice(0, 9), DY = w.slice(9, 18), K = w.slice(18, 27), sx = hc.width / F.w, STEP = 24;
  for (let x0 = F.x; x0 < F.x + F.w; x0 += STEP) {
    const x1 = Math.min(F.x + F.w, x0 + STEP), xc = 0.5 * (x0 + x1);
    const dx = lin(WX, DX, xc), dy = lin(WX, DY, xc), k = lin(WX, K, xc), yr = lin(WX, WY, xc);
    g.save();
    g.transform(1, 0, 0, 1 + k, dx, dy - k * yr);
    const e = x1 < F.x + F.w ? 0.6 : 0;            // a hair of overlap so the slices do not seam
    g.drawImage(hc, (x0 - F.x) * sx, 0, (x1 - x0 + e) * sx, hc.height, x0, F.y, x1 - x0 + e, F.h);
    g.restore();
  }
  g.restore();
}

