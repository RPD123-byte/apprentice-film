// the source's own exposure while locked (source/render mean brightness, measured on every 2nd frame): the frame is ~0.8
// percent darker than the fixed-sine grade gives until 132.00, then ~1.2 percent brighter for a few frames (a step in the
// source at 132.00, when its dark bottom band also vanishes); elsewhere within +-0.4 percent, left alone
const EXPO = [[131.40, 1.0], [131.44, 0.9925], [131.96, 0.9925], [132.00, 1.013], [132.12, 1.013], [132.24, 1.004], [132.32, 1.0]];
function expo(t) {
  if (t < EXPO[0][0] || t >= EXPO[EXPO.length - 1][0]) return 1;
  for (let i = 0; i < EXPO.length - 1; i++) if (t < EXPO[i + 1][0]) {
    const [a, ka] = EXPO[i], [b, kb] = EXPO[i + 1];
    if (b === 132.0) return ka;                                   // a step, not a ramp
    return ka + (kb - ka) * (t - a) / (b - a);
  }
  return 1;
}
