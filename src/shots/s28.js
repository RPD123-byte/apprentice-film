function drawMug(ctx, tf) {
  const k = Math.round((tf - MUGTRACK[0][0]) * 25);
  if (k < 0 || k >= MUGTRACK.length) return;
  const [, u, v, s] = MUGTRACK[k];
  const T = MUGKEYS.map((D) => D.t);
  let i = 0;
  while (i < T.length - 2 && tf > T[i + 1]) i++;
  const w = Math.max(0, Math.min(1, (tf - T[i]) / (T[i + 1] - T[i])));
  ctx.save();
  ctx.imageSmoothingEnabled = true; ctx.imageSmoothingQuality = "high";
  const put = (j, a) => {
    if (a <= 0.002) return;
    const M = mugCanvas(j), sc = s / M.s;
    ctx.globalAlpha = a;
    ctx.setTransform(sc, 0, 0, sc, u + (M.x0 - M.u) * sc, v + (M.y0 - M.v) * sc);
    ctx.drawImage(M.c, 0, 0);
  };
  // the nearer drawing fully, the other one over it at its weight (so the mug never turns see-through)
  if (w < 0.5) { put(i, 1); put(i + 1, w); } else { put(i + 1, 1); put(i, 1 - w); }
  ctx.restore();
}
