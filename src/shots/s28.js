function bbox(rings, pad) {
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (const r of rings) for (const [x, y] of r) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  return [Math.floor(x0 - pad), Math.floor(y0 - pad), Math.ceil(x1 + pad), Math.ceil(y1 + pad)];
}
// a key's measured gain field (s28/keygain.js) as a tiny canvas, or null
function gainCanvas(name, box) {
  const G0 = KEYGAIN[name];
  if (!G0) return null;
  const G = box ? regain(G0, box) : G0;
  const c = canvas(G.w, G.h), g = c.getContext("2d"), px = g.createImageData(G.w, G.h);
  for (let i = 0; i < G.w * G.h; i++) { px.data.set(G.g.slice(i * 3, i * 3 + 3), i * 4); px.data[i * 4 + 3] = 255; }
  g.putImageData(px, 0, 0);
  return c;
}
// resample a key's gain grid (32 px cells over its box x0..x1, y0..y1) onto another box, clamping at the edges
function regain(G, [bx, by, bw, bh]) {
  if (G.x0 === bx && G.y0 === by && G.x1 === bx + bw && G.y1 === by + bh) return G;
  const w = Math.max(2, Math.floor(bw / 32) + 1), h = Math.max(2, Math.floor(bh / 32) + 1), g = new Array(w * h * 3);
  const sx = (G.w - 1) / (G.x1 - G.x0), sy = (G.h - 1) / (G.y1 - G.y0);
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
    const X = bx + i * bw / (w - 1), Y = by + j * bh / (h - 1);
    const fx = Math.max(0, Math.min(G.w - 1, (X - G.x0) * sx)), fy = Math.max(0, Math.min(G.h - 1, (Y - G.y0) * sy));
    const x0 = Math.floor(fx), y0 = Math.floor(fy), x1 = Math.min(G.w - 1, x0 + 1), y1 = Math.min(G.h - 1, y0 + 1), ax = fx - x0, ay = fy - y0;
    for (let c = 0; c < 3; c++) {
      const v = (q, r) => G.g[(r * G.w + q) * 3 + c];
      g[(j * w + i) * 3 + c] = Math.round((v(x0, y0) * (1 - ax) + v(x1, y0) * ax) * (1 - ay) + (v(x0, y1) * (1 - ax) + v(x1, y1) * ax) * ay);
    }
  }
  return { x0: bx, y0: by, x1: bx + bw, y1: by + bh, w, h, g };
}
