// ---------------------------------------------------------------- traced patches with their own clip (end-s28-fix1)
// A patch is one vector trace of a masked area of one source frame (colour regions + ink), cut to its clip polygon(s)
// with a soft edge of `feather` px. Painted on first use, cached per patch.
const PATCHC = new Map();
function patchCanvas(D, feather = 1.2) {
  if (!PATCHC.has(D)) {
    const [x0, y0, x1, y1] = D.box, c = canvas(x1 - x0, y1 - y0), g = c.getContext("2d");
    g.translate(-x0, -y0);
    drawTrace(g, { regions: D.regions });
    const soft = canvas(c.width, c.height), sg = soft.getContext("2d");
    sg.filter = "blur(3px)"; sg.drawImage(c, 0, 0); sg.filter = "none";
    g.save(); g.setTransform(1, 0, 0, 1, 0, 0); g.globalCompositeOperation = "destination-over"; g.drawImage(soft, 0, 0); g.restore();
    drawTrace(g, { ink: D.ink });
    const m = canvas(c.width, c.height), mg = m.getContext("2d");
    mg.translate(-x0, -y0); mg.fillStyle = "#000";
    mg.beginPath(); for (const r of D.clip) r.forEach((p, k) => (k ? mg.lineTo(p[0], p[1]) : mg.moveTo(p[0], p[1]))); mg.closePath(); mg.fill("evenodd");
    let mm = m;
    if (feather > 0) { mm = canvas(c.width, c.height); const f = mm.getContext("2d"); f.filter = `blur(${feather}px)`; f.drawImage(m, 0, 0); f.filter = "none"; }
    g.save(); g.setTransform(1, 0, 0, 1, 0, 0); g.globalCompositeOperation = "destination-in"; g.drawImage(mm, 0, 0); g.restore();
    // fades along the traced box's cut edges (in open room areas they must not show as a line): [side, edge, width]
    for (const [side, e, w] of D.fade || []) {
      g.save(); g.setTransform(1, 0, 0, 1, -x0, -y0); g.globalCompositeOperation = "destination-out";
      const v = side === "t" || side === "b", gr = v ? g.createLinearGradient(0, e, 0, side === "t" ? e + w : e - w) : g.createLinearGradient(e, 0, side === "l" ? e + w : e - w, 0);
      gr.addColorStop(0, "rgba(0,0,0,1)"); gr.addColorStop(1, "rgba(0,0,0,0)"); g.fillStyle = gr;
      if (side === "t") g.fillRect(x0, y0, x1 - x0, e + w - y0);
      else if (side === "b") g.fillRect(x0, e - w, x1 - x0, y1 - e + w);
      else if (side === "l") g.fillRect(x0, y0, e + w - x0, y1 - y0);
      else g.fillRect(e - w, y0, x1 - e + w, y1 - y0);
      g.restore();
    }
    PATCHC.set(D, { c, x0, y0 });
    if (PATCHC.size > 8) PATCHC.delete(PATCHC.keys().next().value);
  }
  return PATCHC.get(D);
}
function drawPatch(ctx, D, feather) {
  const P = patchCanvas(D, feather);
  ctx.save(); ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.drawImage(P.c, P.x0, P.y0); ctx.restore();
}
