#!/usr/bin/env python3
"""Assemble docs/FIDELITY.md from the per-shot logs in docs/fidelity/<id>.md (the first table row of each).

Usage: python3 tools/fidelity_log.py            -> rewrites docs/FIDELITY.md   (npm run fidelity)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = re.findall(r'\["(s\d+)",\s*([\d.]+),\s*([\d.]+),\s*"([^"]*)"\]', (ROOT / "src/shots/index.js").read_text())

HEAD = """# Fidelity log

Everything on screen is drawn by code. No bitmaps, frames, crops or pixels of the original film are embedded. The original
was used for measurements and side-by-side comparison and, in the **traced** and **mixed** shots, as the source of vector
traces (outlines, colour regions and ink strokes stored as numbers and painted by code). The soundtrack is synthesized in
code (see [audio.md](audio.md)).

Per-shot status: **close** = composition, timing, motion and look match closely · **approx** = same shot and staging,
drawing visibly simplified · **simplified** = reduced staging or detail · **cut** = not built.

Per-shot detail (measurements, what was tried, every known gap) lives in [`fidelity/<id>.md`](fidelity/). Paths such as
`snapshots/...` in those logs are the agents' scratch folders, which are not published; the scripts from them are in
[`../tracing/`](../tracing/README.md). This file is generated by `tools/fidelity_log.py` (`npm run fidelity`).

The per-shot logs were written during the build and are kept as written. Folders they mention that are no longer in
`src/` (for example `src/shots/s07/v1/` and `src/shots/s27/drawn/`) now live under `tracing/<id>/src-<id>/` (here
[`../tracing/s07/src-s07/v1/`](../tracing/s07/src-s07/v1/) and [`../tracing/s27/src-s27/drawn/`](../tracing/s27/src-s27/drawn/)).
Remarks in them that a shot awaits the author's sign-off, ruling or approval (s04, s07, s25) are about the tracing
method. The Method column below states the method of every shot.

Method (from each shot's own log and what its code imports): **drawn** = authored drawing code, the source used only
for measurements (positions, timing, values) · **traced** = the imagery is largely built from geometry traced off source
frames (vector traces, rotoscoped keys, contour fits), then redrawn in code · **mixed** = authored drawing combined with
traced geometry for some layers.

| # | Time (s) | Shot | Status | Method | Notes |
|---|---|---|---|---|---|
"""

METHOD = {
    "s02": "drawn", "s05": "drawn", "s13": "drawn", "s19": "drawn", "s20": "drawn", "s21": "drawn", "s23": "drawn",
    "s04": "traced", "s06": "traced", "s07": "traced", "s08": "traced", "s12": "traced", "s16": "traced", "s18": "traced",
    "s22": "traced", "s26": "traced", "s27": "traced", "s28": "traced",
    "s01": "mixed", "s09": "mixed", "s14": "mixed", "s15": "mixed", "s17": "mixed", "s24": "mixed",
    "s25": "mixed",  # owl drawings in src/shots/s25/v2/data/ are measured outlines + ink lines (extract3.py)
    "s40": "mixed",
}


def row_for(sid, a, b, title):
    p = ROOT / "docs" / "fidelity" / f"{sid}.md"
    if not p.exists():
        return f"| {sid} | {float(a):.2f}–{float(b):.2f} | {title} | cut | – | no fidelity log |", 'cut'
    txt = p.read_text()
    for line in txt.splitlines():
        if line.startswith("|") and re.match(rf"\|\s*{sid}\s*\|", line):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            status = next((c for c in cells[3:4] + cells
                           if re.match(r"(close|approx|simplified|cut)\b", c.lower())), "?")
            notes = cells[-1] if len(cells) >= 5 else ""
            notes = re.sub(r"\s+", " ", notes)
            key = (re.match(r"[a-z]+", status.lower()) or [status])[0]
            return f"| [{sid}](fidelity/{sid}.md) | {float(a):.2f}–{float(b):.2f} | {title} | {status} | {METHOD.get(sid, '?')} | {notes} |", key
    return f"| [{sid}](fidelity/{sid}.md) | {float(a):.2f}–{float(b):.2f} | {title} | ? | {METHOD.get(sid, '?')} | (no table row in fidelity/{sid}.md) |", '?'


def tally_line(keys):
    n, sec = {}, {}
    for k, (a, b) in keys:
        n[k] = n.get(k, 0) + 1
        sec[k] = sec.get(k, 0) + float(b) - float(a)
    return ", ".join(f"{k}: {v} shots / {sec[k]:.1f} s" for k, v in n.items())


rows, by_status, by_method = [], [], []
for sid, a, b, title in PLAN:
    r, st = row_for(sid, a, b, title)
    rows.append(r)
    by_status.append((st, (a, b)))
    by_method.append((METHOD.get(sid, '?'), (a, b)))

summary = tally_line(by_status)
order = {"traced": 0, "mixed": 1, "drawn": 2}
methods = tally_line(sorted(by_method, key=lambda m: order.get(m[0], 3)))
(ROOT / "docs" / "FIDELITY.md").write_text(HEAD + "\n".join(rows)
                                           + f"\n\n**Totals** — {summary}. **By method** — {methods}.\n")
print(summary)
print(methods)
