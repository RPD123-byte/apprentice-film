#!/usr/bin/env python3
# tojs.py key.json out.js NAME -- write a traced key as a compact JS module (rings: delta-coded printable strings).
# Ring code: each ring = 4 chars absolute start (2 base-91 digits per coordinate, offset 1000), then one char per
# delta coordinate (range -45..45; longer jumps are split into collinear steps), rings separated by a space.
import json, sys
ALPHA = [chr(c) for c in range(35, 127) if c != 92]   # 91 printable chars, no backslash / quote
assert len(ALPHA) == 91
def enc_num2(v):
    v = int(v) + 1000; assert 0 <= v < 91 * 91, v
    return ALPHA[v // 91] + ALPHA[v % 91]
def enc_ring(r):
    # v2: 4 chars start; then per point one char for a step within +-4 px (9x9 codes), or ALPHA[81] + two chars
    # (+-45 px); longer jumps are split into collinear steps
    s = enc_num2(r[0][0]) + enc_num2(r[0][1])
    px, py = r[0]
    for x, y in r[1:]:
        dx, dy = x - px, y - py
        n = max(1, -(-max(abs(dx), abs(dy)) // 45))
        qx0, qy0 = px, py
        for k in range(1, n + 1):
            qx = px + round(dx * k / n); qy = py + round(dy * k / n)
            ex, ey = qx - qx0, qy - qy0
            if abs(ex) <= 4 and abs(ey) <= 4: s += ALPHA[(ex + 4) * 9 + (ey + 4)]
            else: s += ALPHA[81] + ALPHA[ex + 45] + ALPHA[ey + 45]
            qx0, qy0 = qx, qy
        px, py = x, y
    return s
def enc_group(rings): return " ".join(enc_ring(r) for r in rings if len(r) >= 3)
K = json.load(open(sys.argv[1])); out = sys.argv[2]; name = sys.argv[3]
def groups(lst): return [[round(b["v"]), enc_group(b["rings"])] for b in lst if b["rings"]]
hull = K["hull"]; hull = [hull] if isinstance(hull[0][0], (int, float)) else hull
data = {"enc": 2, "t": K["t"], "hull": hull, "cut": K.get("cut", []), "tone": groups(K["tone"]), "inkd": groups(K.get("inkd", [])), "inkb": groups(K.get("inkb", []))}
if K.get("full"):
    data["full"] = 1
    import os
    if K.get("dirs") and not os.environ.get("NOENGRAVE"):
        D = K["dirs"]; data["dgrid"] = [D["nx"], D["ny"], D["step"]]; data["dirs"] = "".join(ALPHA[v] for v in D["v"])
        if "w" in D: data["dw"] = "".join(ALPHA[v] for v in D["w"])
        if "s" in D: data["ds"] = "".join(ALPHA[v] for v in D["s"])
    if K.get("fig"): data["fig"] = [K["fig"]] if isinstance(K["fig"][0][0], (int, float)) else K["fig"]
if K.get("flows"):
    fl = {}
    for o, F in K["flows"].items():
        # v2: per component (x then y planes), row-major deltas in 1/4 px: one char for -40..40, else ALPHA[81..]
        # escape + 2 chars absolute (offset 4000)
        vals = F["v"]; xs_ = vals[0::2]; ys_ = vals[1::2]; fo = []
        for plane in (xs_, ys_):
            prev = 0
            for v in plane:
                d = v - prev
                if -40 <= d <= 40: fo.append(ALPHA[d + 40])
                else: fo.append(ALPHA[81] + ALPHA[(v + 4000) // 91] + ALPHA[(v + 4000) % 91])
                prev = v
        fl[o] = "".join(fo)
        data["fgrid"] = [F["nx"], F["ny"], F["step"]]
    data["flows"] = fl
txt = json.dumps(data, separators=(",", ":"))
hdr = f"""// s04 traced key {K['t']:.2f} s: the designer (and the owl on his shoulder) MEASURED on that source frame and stored as
// outlines only — a smooth value study (tone bands) plus the ink marks darker / paler than it — no pixels.
// Ring strings: see s04/tkey.js (decode). Generated by snapshots/s04-k2/tr (trace_key.py + tojs.py).
"""
open(out, "w").write(hdr + f"export const {name} = " + txt + ";\n")
print(out, len(txt), "bytes")
