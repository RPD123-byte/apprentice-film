# export_vis.py: the traced-visible masks (the part of a layer the tracer saw) of some layers, inside sub-boxes, as
# rings (same packing as trace/export.py) -> src/shots/s05/data/vis.js
import sys, pickle, numpy as np, cv2, json
sys.path.insert(0,'/Users/computer/rootline/apprentice-film/src/shots/s05/trace')
from export import rings_str
C='/Users/computer/rootline/apprentice-film/snapshots/s05-p2-study/cache'
REG={'desk':(1240,470,1710,820),'fig':(1150,480,1700,946),'owl':(1360,170,1820,740),'rhB':(840,540,1300,800)}
out=['// s05: the parts of some layers the tracer saw (the rest of each layer is filled in), as outlines inside a sub-box',
     '// (frame px of the box corner; rings relative to it). GENERATED by snapshots/s05-fix1n-study/export_vis.py from the',
     '// layer masks of the trace build. Used to repaint filled-in parts (s05/layers.js).','export const VIS = {']
for name,(bx0,by0,bx1,by1) in REG.items():
    L=pickle.load(open(f'{C}/layer_{name}.pkl','rb')); x0,y0,x1,y1=L['box']
    v=L['vis'][by0-y0:by1-y0, bx0-x0:bx1-x0].astype(np.uint8)
    v=cv2.morphologyEx(v,cv2.MORPH_OPEN,np.ones((3,3),np.uint8))
    cs,_=cv2.findContours(v,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_NONE)
    rings=[cv2.approxPolyDP(c,0.8,True)[:,0,:].astype(np.float32)+0.5 for c in cs if abs(cv2.contourArea(c))>30]
    out.append(f'  {name}: {{ box: {json.dumps([bx0,by0,bx1,by1])}, rings: {json.dumps(rings_str(rings))} }},')
    print(name,len(rings),sum(len(r) for r in rings))
out.append('};\n')
open('/Users/computer/rootline/apprentice-film/src/shots/s05/data/vis.js','w').write('\n'.join(out))
