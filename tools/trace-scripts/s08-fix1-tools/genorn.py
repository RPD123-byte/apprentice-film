# ---- the ribbon (U + pastel tail): the page's five boundary lines refined onto the first frame (rib2/rib3.py),
# and each band's page-space colour sampled along its length (rib4.py)
bounds=list(np.load('snapshots/s08-fix1-tools/rib_bounds.npy',allow_pickle=True))
bands=list(np.load('snapshots/s08-fix1-tools/rib_bands.npy',allow_pickle=True))
def rs(c,step=8.0):
  d=np.r_[0,np.cumsum(np.hypot(*np.diff(c,axis=0).T))]; s_=np.r_[np.arange(0,d[-1],step),d[-1]]
  return np.stack([np.interp(s_,d,c[:,0]),np.interp(s_,d,c[:,1])],1)
txt=open('src/shots/s08/ornaments.js').read()
txt+='// The ribbon: the U and its pastel tail. RIB_B = the five boundary lines (outer pink edge ... inner yellow/cream\n'
txt+='// edge), refined from pureimg\'s layout onto the first frame (normal offsets, smoothed); RIB_C = per band, samples\n'
txt+='// along it [x, y, width, r, g, b] of the page-space colour measured on the source. F0 px.\n'
txt+='export const RIB_B = [\n'+'\n'.join('  ['+','.join('%.1f'%v for v in rs(b).reshape(-1))+'],' for b in bounds)+'\n];\n'
