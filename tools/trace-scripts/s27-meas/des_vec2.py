# Designer v2 measurement (125.0 s): ink layer (dark mask contours, sub-pixel), soft-line layer, colour regions.
import cv2, numpy as np, json
from common import load
from ungrade import ungrade, hexc
T=125.0
f=load(T); g=cv2.cvtColor(f,cv2.COLOR_BGR2GRAY)
pts=json.load(open('sil125.json'))
mask=np.zeros(g.shape,np.uint8); cv2.fillPoly(mask,[np.int32(np.round(pts))],255)
lab=cv2.cvtColor(cv2.GaussianBlur(f,(5,5),0),cv2.COLOR_BGR2LAB).astype(np.float32)
chroma=np.hypot(lab[...,1]-128,lab[...,2]-128)
wall=((lab[...,0]>200)&(chroma<14)).astype(np.uint8); wall=cv2.morphologyEx(wall,cv2.MORPH_OPEN,np.ones((5,5),np.uint8))
mask[wall>0]=0; mask=cv2.morphologyEx(mask,cv2.MORPH_OPEN,np.ones((3,3),np.uint8))
S=3
def contours_of(m, eps, minarea, smooth=0.8):
    M=cv2.resize(m.astype(np.float32),None,fx=S,fy=S,interpolation=cv2.INTER_LINEAR)
    if smooth: M=cv2.GaussianBlur(M,(0,0),smooth*S)
    B=(M>0.5).astype(np.uint8)
    cnts,hier=cv2.findContours(B,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_NONE)
    out=[]
    if hier is None: return out
    for i,c in enumerate(cnts):
        if hier[0][i][3]>=0: continue
        if cv2.contourArea(c)<minarea*S*S: continue
        o=cv2.approxPolyDP(c,eps*S,True).reshape(-1,2)/S
        holes=[]; j=hier[0][i][2]
        while j>=0:
            if cv2.contourArea(cnts[j])>=minarea*S*S*0.5: holes.append((cv2.approxPolyDP(cnts[j],eps*S,True).reshape(-1,2)/S))
            j=hier[0][j][0]
        out.append((o,holes))
    return out
# ink: very dark pixels + thin dark lines
bh=cv2.morphologyEx(g,cv2.MORPH_BLACKHAT,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(9,9)))
Gs=g.astype(np.float32)
ink=((Gs<38)|((bh>34)&(Gs<110))).astype(np.float32)*(mask>0)
# soft lines: brownish mid-dark thin lines (face modelling, blush hatching, fabric folds)
soft=(((bh>16)&(Gs<175))&~(ink>0)).astype(np.float32)*(mask>0)
inkC=contours_of(ink,0.35,1.5,0.5)
softC=contours_of(soft,0.45,3,0.6)
# colour: inpaint the ink+soft, then cluster
im=((ink>0)|(soft>0)).astype(np.uint8)*255; im=cv2.dilate(im,np.ones((3,3),np.uint8))
clean=cv2.inpaint(f,im,4,cv2.INPAINT_TELEA); clean=cv2.bilateralFilter(clean,9,30,7)
L=cv2.cvtColor(clean,cv2.COLOR_BGR2LAB).astype(np.float32)
ys,xs=np.nonzero(mask)
cv2.setRNGSeed(3)
K=22
_,lb,cen=cv2.kmeans(L[ys,xs],K,None,(cv2.TERM_CRITERIA_EPS+cv2.TERM_CRITERIA_MAX_ITER,50,0.3),4,cv2.KMEANS_PP_CENTERS)
Lb=np.full(g.shape,-1,np.int32); Lb[ys,xs]=lb.ravel()
for it in range(2):
    votes=np.stack([cv2.boxFilter((Lb==k).astype(np.float32),-1,(5,5)) for k in range(K)])
    Lb=np.where(mask>0,np.argmax(votes,0),-1)
bgr=cv2.cvtColor(cen.reshape(1,-1,3).astype(np.uint8),cv2.COLOR_LAB2BGR).reshape(-1,3)
regions=[]
for k in range(K):
    for o,h in contours_of((Lb==k).astype(np.float32),0.7,30,0.9):
        M=np.zeros(g.shape,np.uint8); cv2.fillPoly(M,[np.int32(o)],1)
        yy,xx=np.nonzero(M)
        if len(xx)==0: continue
        # region colour = mean of the clean image inside (more faithful than the centre)
        col=clean[yy,xx].mean(0)[::-1]; cx,cy=xx.mean(),yy.mean()
        regions.append({'c':hexc(ungrade(col,cx,cy)),'a':int(len(xx)),'p':o,'h':h})
regions.sort(key=lambda r:-r['a'])
def mean_col(C,src):
    out=[]
    for o,h in C:
        M=np.zeros(g.shape,np.uint8); cv2.fillPoly(M,[np.int32(np.round(o))],1)
        yy,xx=np.nonzero(M)
        col=src[yy,xx].mean(0)[::-1] if len(xx) else np.array([30,25,22])
        out.append((o,h,hexc(ungrade(col,xx.mean() if len(xx) else 0,yy.mean() if len(xx) else 0))))
    return out
softC2=mean_col(softC,cv2.GaussianBlur(f,(3,3),0))
outl=contours_of((mask>0).astype(np.float32),0.6,200,1.0)
def fl(a): return [int(round(v*4)) for xy in a for v in xy]
data={'regions':[[r['c'],fl(r['p'])]+[fl(x) for x in r['h']] for r in regions],
      'ink':[[fl(o)]+[fl(x) for x in h] for o,h in inkC],
      'soft':[[c,fl(o)]+[fl(x) for x in h] for o,h,c in softC2],
      'outline':[fl(o) for o,h in outl]}
n=lambda arr: sum(len(p) for item in arr for p in item if isinstance(p,list))//2
print('regions',len(regions),'ink',len(inkC),'soft',len(softC),'pts',n(data['regions']),n(data['ink']),n(data['soft']))
js=["// The designer at 125.0 s, measured (traced) on the source frame. Coordinates are frame px x4 (integers).",
"// DES_REGIONS: flat colour areas [colour, outer, ...holes] (pre-grade colours, area-mean of the de-inked frame),",
"// DES_INK: the black line art and hair masses as filled polygons [outer, ...holes],",
"// DES_SOFT: the thinner brown modelling lines [colour, outer, ...holes], DES_OUTLINE: the figure outline.",
"// Generated by snapshots/s27-meas/des_vec2.py; drawn by code in designer.js.",
"export const DES_REGIONS = "+json.dumps(data['regions'],separators=(',',':'))+";",
"export const DES_INK = "+json.dumps(data['ink'],separators=(',',':'))+";",
"export const DES_SOFT = "+json.dumps(data['soft'],separators=(',',':'))+";",
"export const DES_OUTLINE = "+json.dumps(data['outline'],separators=(',',':'))+";"]
open('/Users/computer/rootline/apprentice-film/src/shots/s27/designerData.js','w').write("\n".join(js)+"\n")
