# resid.json -> src/shots/s28/resid.js (base64 int8, 0.5 px units; dx block then dy block, every 2nd vertex)
import json, base64, numpy as np
R = json.load(open('resid.json'))
out = {}
for name, d in R.items():
    out[name] = {t: [nu, nv, base64.b64encode(np.array(q, np.int8).tobytes()).decode()] for t, (nu, nv, q) in d.items()}
js = ("// Generated by snapshots/s28-k-tools/resid.py + emitresid.py. Measured screen-space residuals of the orbit's key\n"
      "// re-projection: for each key and each frame it is drawn in, the offset (px) between where the 3D re-projection puts each\n"
      "// mesh vertex and where KLT tracks on the source (key frame warped by the prediction -> that frame, forward/backward\n"
      "// checked, only where the key's layer is visible) say it is; smoothed on the grid. Every 2nd vertex, int8 in 0.5 px,\n"
      "// base64: all dx, then all dy. Motion measurement only (no image data).\n"
      "export const RESID = " + json.dumps(out, separators=(',', ':')) + ";\n")
open('/Users/computer/rootline/apprentice-film/src/shots/s28/resid.js', 'w').write(js)
print(len(js), 'bytes', sum(len(d) for d in out.values()), 'entries')
