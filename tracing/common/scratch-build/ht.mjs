// The lift onto the keys: 3.80 the hand rises off the trackpad (blurred), 3.84–4.08 it rests on the keys (pose 2,
// traced separately), 4.12 it is back on the trackpad, sharp.
const LIFT = [[3.76, 0], [3.8, -22], [3.82, -30]];
const tab = (T, t, k) => {
  if (t <= T[0][0]) return T[0][k];
  for (let i = 1; i < T.length; i++) if (t <= T[i][0]) { const a = T[i - 1], b = T[i]; return a[k] + (b[k] - a[k]) * ((t - a[0]) / (b[0] - a[0])); }
  return T[T.length - 1][k];
};
function handPose(t) {
  if (t >= 3.82 && t < 4.1) return { pose: 2, dx: 0, dy: 0 };
  const lift = t > 3.76 && t < 3.82 ? tab(LIFT, t, 1) : 0;
  return { pose: 1, dx: tab(HT, t, 1), dy: tab(HT, t, 2) + lift };
}

