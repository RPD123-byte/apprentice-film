function shirtStrokes(g, left, right, seed) {
  // long feathery fold strokes falling from the shoulder lines
  let x = seed; const rr = () => (x = (x * 16807) % 2147483647) / 2147483647;
  for (let i = 0; i < 150; i++) {
    const L0 = i % 2 === 0 ? left : right;
    if (!L0) continue;
    const u = rr(), p = [L0[0][0] + (L0[1][0] - L0[0][0]) * u, L0[0][1] + (L0[1][1] - L0[0][1]) * u];
    const x0 = p[0] + (rr() - 0.5) * 30, y0 = p[1] + 10 + rr() * 60, L = 40 + rr() * 110, a = Math.PI / 2 + (L0[2] || 0) * (0.6 + rr()) + (rr() - 0.5) * 0.4;
    strand(g, [[x0, y0], [x0 + Math.cos(a) * L * 0.5, y0 + Math.sin(a) * L * 0.5 + 3], [x0 + Math.cos(a) * L, y0 + Math.sin(a) * L]], 0.9 + 0.7 * rr(), gv(0.12, 0.3 + 0.3 * rr()), { per: 3, head: 0.15 });
  }
}
function ear(g, pts, inner) {
  fillPath(g, blob(pts), gv(0.93));
  clipTo(g, blob(pts), () => { g.save(); g.filter = "blur(8px)"; g.fillStyle = gv(0.5, 0.5); g.beginPath(); smoothPath(g, inner, true); g.fill(); g.restore(); });
  line(g, [...pts.slice(0, 5)], 2.4, INKC, { end: 0.3 });
  line(g, inner, 2.0, INKC, { end: 0.2 });
}

