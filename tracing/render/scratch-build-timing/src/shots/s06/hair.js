// widths per control point: a lock is full width at the root (under the brim) and ends in a point
const prof = (n, w, { tip = 0.04, keep = 0.35, pow = 1.2 } = {}) => Array.from({ length: n }, (_, i) => {
  const u = i / (n - 1);
  return u < keep ? w : w * (tip + (1 - tip) * Math.pow(Math.cos((Math.PI / 2) * (u - keep) / (1 - keep)), pow));
});
function L(g, pts, w, o = {}) { vline(g, pts, Array.isArray(w) ? w : prof(pts.length, w, o), o.color || INKC, 8); }
// a strand: tapered at both ends
function strand(g, pts, w, color) { taper(g, sampleCurve(pts, 8), (u) => w * Math.pow(Math.sin(Math.PI * Math.min(1, Math.max(0, u))), 0.55), color); }

