export function drawHair(g) {
  const r = rng(13);
  // grey strand texture first (under the black locks)
  for (const [pts, w, a] of [...CENTRE_GREY, ...CHEEK_GREY]) strand(g, pts, w, `rgba(30,30,30,${a})`);
  // grey hair texture over the right cheek: fine strands leaving the mass's inner edge, down and to the left
  for (let i = 0; i < 80; i++) {
    const y = 250 + r() * 420, x = 1345 + (y - 250) * 0.03 + r() * 40;
    const a = 1.82 + 0.25 * r() + (y - 450) * 0.0004, L0 = 60 + r() * 120, b = (r() - 0.5) * 18;
    const ca = Math.cos(a), sa = Math.sin(a);
    strand(g, [[x, y], [x + ca * L0 * 0.5 - sa * b, y + sa * L0 * 0.5 + ca * b], [x + ca * L0, y + sa * L0]], 0.7 + r() * 1.1, `rgba(25,25,25,${0.22 + 0.3 * r()})`);
  }
  // and over the left temple, by the face edge
  for (let i = 0; i < 24; i++) {
    const y = 240 + r() * 200, x = 772 + r() * 26;
    const a = 1.5 + 0.2 * r(), L0 = 40 + r() * 70;
    strand(g, [[x, y], [x + Math.cos(a) * L0 * 0.5 + 3, y + Math.sin(a) * L0 * 0.5], [x + Math.cos(a) * L0 + 5, y + Math.sin(a) * L0]], 0.7 + r() * 0.9, `rgba(25,25,25,${0.2 + 0.3 * r()})`);
  }
  // black locks
  for (const [pts, w, o] of [...LEFT, ...FRINGE, ...RIGHT]) L(g, pts, w, o || {});
  for (const [pts, w] of CENTRE) L(g, pts, w);
  // fine dark strands trailing some locks
  for (const [pts, w, o] of [...FRINGE, ...RIGHT, ...CENTRE, ...LEFT]) {
    const rr = rng(Math.round(pts[0][0] * 7 + pts[0][1]));
    for (let k = 0; k < 2; k++) {
      const ww = typeof w === "number" ? w : Math.max(...w) * 0.4, off = (rr() - 0.5) * ww * 1.1;
      strand(g, pts.map(([x, y], j) => [x + off * (1 + j * 0.12) + j * 2 * (rr() - 0.5), y + j * 3]), 0.8 + rr() * 1.1, "rgba(10,10,10,0.8)");
    }
  }
  // gaps between the right clumps
  for (const [pts, w] of GAPS) strand(g, pts, w, "rgba(214,213,208,0.9)");
  // sheen: thin light strands inside the wide locks
  for (const [pts, w, a] of [...LEFT_SHEEN, ...FRINGE_SHEEN, ...CENTRE_SHEEN, ...RIGHT_SHEEN, ...LOW_SHEEN]) strand(g, pts, w, `rgba(${SHEEN},${a})`);
  // and a few very fine ones beside them (split ends of the highlight)
  for (const [pts, w, a] of [...LEFT_SHEEN, ...FRINGE_SHEEN, ...CENTRE_SHEEN, ...RIGHT_SHEEN]) {
    if (r() < 0.45) continue;
    const off = (r() < 0.5 ? -1 : 1) * (3 + r() * 4);
    strand(g, pts.map(([x, y], j) => [x + off, y + j * 1.5]).slice(0, Math.max(2, pts.length - 1)), 0.8, `rgba(${SHEEN},${a * 0.6})`);
  }
  // jaw strands
  for (const [pts, w, a] of JAW) L(g, pts, w, { keep: 0.15, color: `rgba(8,8,8,${a})` });
}
