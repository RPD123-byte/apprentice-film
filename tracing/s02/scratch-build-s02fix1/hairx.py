import cv2, numpy as np, json
S=cv2.imread('src/f200.png',0).astype(np.float32)
B=cv2.GaussianBlur(S,(0,0),1.3)
D=(B<95).astype(np.uint8)
Z=np.zeros_like(D)
cuff=[(560,372),(600,372),(612,340),(625,300),(640,265),(660,224),(680,202),(700,179),(720,170),(740,156),(760,143),(780,133),(800,126),(820,117),(840,113),(860,107),(880,103),(900,99),(940,92),(980,85),(1000,83),(1100,84),(1160,90),(1220,101),(1240,109),(1260,115),(1280,121),(1300,130),(1320,141),(1340,151),(1360,164),(1380,178),(1400,201),(1420,215),(1440,248),(1458,295),(1468,332),(1478,357),(1570,357)]
up=[(x,y-14) for x,y in cuff]           # the beanie is painted over the hair, so the zone may run under the cuff
zone=up+[(1570,800),(1290,800),(1300,640),(1300,480),(1180,480),(1120,470),(960,490),(880,490),(800,480),(800,800),(540,800),(540,358)]
cv2.fillPoly(Z,[np.array(zone,np.int32)],1)
# leave out: the eyes with their lids (ellipses), the brows (bands), sweat, nose, pencil
cv2.ellipse(Z,(845,321),(100,52),0,0,360,0,-1)
cv2.ellipse(Z,(1234,318),(100,52),0,0,360,0,-1)
cv2.fillPoly(Z,[np.array([(842,186),(875,184),(905,193),(932,208),(952,232),(948,246),(925,232),(898,217),(868,208),(842,204)],np.int32)],0)
cv2.fillPoly(Z,[np.array([(1104,232),(1112,212),(1140,195),(1175,181),(1215,172),(1255,172),(1258,190),(1215,192),(1178,202),(1146,216),(1118,238)],np.int32)],0)
for (x0,y0,x1,y1) in [(905,138,930,168),(1132,136,1156,172),(1158,100,1178,126),(1100,392,1128,442),(955,470,1140,630),(700,704,1400,752)]:
    Z[y0:y1,x0:x1]=0
m=D*Z
m=cv2.morphologyEx(m,cv2.MORPH_OPEN,np.ones((2,2),np.uint8))
n,lab,st,_=cv2.connectedComponentsWithStats(m,8)
polys=[]
for c in range(1,n):
    if st[c,4]<25: continue
    mm=(lab==c).astype(np.uint8)
    cs,hier=cv2.findContours(mm,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_NONE)
    for i,(h,hh) in enumerate(zip(cs,hier[0])):
        if hh[3]>=0: continue
        big=cv2.contourArea(h)>2000
        ap=cv2.approxPolyDP(h,2.0 if big else 1.2,True)[:,0,:]
        if len(ap)<3: continue
        holes=[cv2.approxPolyDP(g,1.3,True)[:,0,:].tolist() for g,gg in zip(cs,hier[0]) if gg[3]==i and cv2.contourArea(g)>30]
        polys.append({'o':ap.tolist(),'h':[x for x in holes if len(x)>=3],'a':int(st[c,4]),'c':np.array(ap).mean(0).tolist()})
polys.sort(key=lambda p:-p['a'])
print(len(polys),[(p['a'],[int(v) for v in p['c']]) for p in polys[:5]])
def flat(p): return '['+','.join(f'{int(x)},{int(y)}' for x,y in p)+']'
out=['// s02 designer: the dark hair masses of the stare frame, MEASURED from the source at 8.0 s (not hand-traced):',
'// dark runs (gaussian 1.3 px, < 95/255) inside a hand-drawn hair zone that leaves out the eyes (ellipses), brows,',
'// sweat, nose and pencil; outlines simplified to 2 px (big masses) / 1.2 px (small pieces). Flat [x0,y0,x1,y1,...]',
'// world px. Each piece: outer outline + the light partings/gaps inside it (cut out with evenodd). Generated by the',
'// scratch script s02fix1/hairx.py; the thin strands, partings and flyaways are inked on top in designer.js.',
'export const HAIR = [']
for p in polys: out.append('  { o: '+flat(p['o'])+', h: ['+', '.join(flat(h) for h in p['h'])+'] },')
out.append('];')
big=polys[:3]; idx={}
for i,p in enumerate(big):
    x=p['c'][0]; idx['R' if x>1300 else 'L' if x<800 else 'F']=i
out.append(f"export const HAIR_R = HAIR[{idx['R']}].o, HAIR_L = HAIR[{idx['L']}].o, HAIR_F = HAIR[{idx['F']}].o;")
open('/Users/computer/rootline/apprentice-film/src/shots/s02/hairShapes.js','w').write('\n'.join(out)+'\n')
vis=cv2.cvtColor(S.astype(np.uint8),cv2.COLOR_GRAY2BGR)
for p in polys:
    cv2.polylines(vis,[np.array(p['o'],np.int32)],True,(0,0,255),1)
cv2.imwrite('hairpoly4_vis.jpg',vis[60:800,520:1580],[cv2.IMWRITE_JPEG_QUALITY,85])
print(idx)
