#!/usr/bin/env python3
# fitfaces.py FACES.json OUT.js NAME [REF]: fit a value grid (pre-grade, blurred sigma 4) to every face of FACES.json on
# the ungraded reference; writes OUT.js: export const NAME = { face: [nu, nv, [values row-major, v then u]] }
# Faces with "poly": the polygon's value is fitted as a bilinear over its bounding quad (bbox corners).
import sys, json, numpy as np, cv2
sys.path.insert(0,'.')
faces=json.load(open(sys.argv[1])); out=sys.argv[2]; NAME=sys.argv[3]; ref=sys.argv[4] if len(sys.argv)>4 else 'TB'
u=np.load(f'{ref}_u.npy').mean(2); ub=cv2.GaussianBlur(u,(0,0),4); H,W=u.shape
def inv_bil(px,py,q):
    a,b,c,d=[np.array(p,float) for p in q]
    uu=np.full(px.shape,0.5); vv=np.full(px.shape,0.5)
    for _ in range(15):
        P=(1-vv)[...,None]*((1-uu)[...,None]*a+uu[...,None]*b)+vv[...,None]*((1-uu)[...,None]*d+uu[...,None]*c)
        du=(1-vv)[...,None]*(b-a)+vv[...,None]*(c-d); dv=(1-uu)[...,None]*(d-a)+uu[...,None]*(c-b)
        rx=px-P[...,0]; ry=py-P[...,1]; det=du[...,0]*dv[...,1]-du[...,1]*dv[...,0]; det[det==0]=1e-6
        uu+=(rx*dv[...,1]-ry*dv[...,0])/det; vv+=(-rx*du[...,1]+ry*du[...,0])/det
    return np.clip(uu,0,1),np.clip(vv,0,1)
def tent(t,n):
    B=np.zeros((len(t),n))
    if n==1: B[:,0]=1; return B
    f=np.clip(t,0,1)*(n-1); i0=np.minimum(np.floor(f).astype(int),n-2); w=f-i0
    B[np.arange(len(t)),i0]=1-w; B[np.arange(len(t)),i0+1]=w; return B
excl=None
if len(sys.argv)>5: excl=cv2.imread(sys.argv[5],0)   # optional mask of pixels to ignore (white = ignore)
res={}
for name,f in faces.items():
    q=f['q']; nu,nv=[int(x) for x in f['g'].split('x')]
    m=np.zeros((H,W),np.uint8); cv2.fillPoly(m,[np.array(q,np.int32)],1)
    m=cv2.erode(m,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(5,5)))
    if excl is not None: m[excl>127]=0
    ys,xs=np.nonzero(m)
    if len(xs)<20: print('skip',name); res[name]=[1,1,[0.0]]; continue
    if f.get('poly'):
        x0,y0,x1,y1=min(p[0] for p in q),min(p[1] for p in q),max(p[0] for p in q),max(p[1] for p in q)
        uu=(xs-x0)/(x1-x0); vv=(ys-y0)/(y1-y0)
    else: uu,vv=inv_bil(xs+0.5,ys+0.5,q)
    y=ub[ys,xs]; A=(tent(vv,nv)[:,:,None]*tent(uu,nu)[:,None,:]).reshape(len(xs),nu*nv)
    c=np.linalg.solve(A.T@A+1e-3*len(xs)*np.eye(nu*nv),A.T@y); c=np.clip(c,0,1)
    r=y-A@c
    res[name]=[nu,nv,[round(float(v),3) for v in c]]
    print(f'{name:10s} mean {y.mean():.3f} rms {np.sqrt((r**2).mean()):.3f} n {len(xs)}')
with open(out,'w') as fo:
    fo.write('// GENERATED by snapshots/s05-fix1d-study/fitfaces.py: per-face value grids [nu, nv, values (row-major, v rows of u)],\n')
    fo.write('// least-squares fits of the pre-grade light over each face (the source rest frame, blurred 4 px): control values only.\n')
    fo.write(f'export const {NAME} = {{\n'+',\n'.join(f'  {k}: {json.dumps(v)}' for k,v in res.items())+'\n};\n')
