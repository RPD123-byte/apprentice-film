#!/usr/bin/env python3
# fitfield.py REGIONS.json OUT.js NAME [REF]: for each region {name: {"poly": [[x,y]...], "S": spacing px (>= 40)}}
# fit a coarse value grid (bilinear, spacing S, Laplacian-smoothed) to the pre-grade light inside the polygon of the
# ungraded reference (blurred 4 px). Writes OUT.js: export const NAME = { region: [x0, y0, S, nx, ny, [values]] }.
# These are light measurements at >= 40 px resolution (control values only), like s02's fitted tone gaussians.
import sys, json, numpy as np, cv2
from scipy.sparse import lil_matrix, csr_matrix, vstack
from scipy.sparse.linalg import lsqr
regs=json.load(open(sys.argv[1])); GEX=regs.pop('_excl',[]); out=sys.argv[2]; NAME=sys.argv[3]; ref=sys.argv[4] if len(sys.argv)>4 and not sys.argv[4].startswith('--') else 'TB'
u=np.load(f'{ref}_u.npy').mean(2).astype(np.float32); H,W=u.shape
PAPER='--paper' in sys.argv
if PAPER:
    # the paper under the ink: a grey closing (thin dark lines removed), then blurred
    k=cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(7,7)); u=cv2.morphologyEx(u,cv2.MORPH_CLOSE,k)
ub=cv2.GaussianBlur(u,(0,0),4)
res={}
for name,R in regs.items():
    poly=np.array(R['poly'],np.int32); S=R.get('S',48); lam=R.get('lam',0.3)
    x0,y0=poly.min(0)-S//2; x1,y1=poly.max(0)+S//2
    nx=int(np.ceil((x1-x0)/S))+1; ny=int(np.ceil((y1-y0)/S))+1
    m=np.zeros((H,W),np.uint8); cv2.fillPoly(m,[poly],1); m=cv2.erode(m,np.ones((5,5),np.uint8))
    for ex in R.get('excl',[])+([] if R.get('noglobal') else GEX): cv2.fillPoly(m,[np.array(ex,np.int32)],0)
    ys,xs=np.nonzero(m); ys=ys[::3]; xs=xs[::3]
    fx=(xs-x0)/S; fy=(ys-y0)/S; i0=np.clip(np.floor(fx).astype(int),0,nx-2); j0=np.clip(np.floor(fy).astype(int),0,ny-2); ax=fx-i0; ay=fy-j0
    n=len(xs); A=lil_matrix((n,nx*ny))
    for (di,dj,w) in [(0,0,(1-ax)*(1-ay)),(1,0,ax*(1-ay)),(0,1,(1-ax)*ay),(1,1,ax*ay)]:
        A[np.arange(n),(j0+dj)*nx+(i0+di)]=w
    # smoothness
    L=lil_matrix((nx*ny*2,nx*ny)); r=0
    for j in range(ny):
        for i in range(nx):
            if i+1<nx: L[r,j*nx+i]=-1; L[r,j*nx+i+1]=1; r+=1
            if j+1<ny: L[r,j*nx+i]=-1; L[r,(j+1)*nx+i]=1; r+=1
    L=L[:r]
    y=ub[ys,xs]
    M=vstack([csr_matrix(A),csr_matrix(L)*np.sqrt(lam*n/max(1,r))])
    b=np.concatenate([y,np.zeros(r)])
    c=lsqr(M,b,atol=1e-8,btol=1e-8,iter_lim=5000)[0]
    c=np.clip(c,0,1); pred=np.asarray(csr_matrix(A)@c).ravel()
    print(f'{name:10s} grid {nx}x{ny} S{S} mean {y.mean():.3f} rms {np.sqrt(((y-pred)**2).mean()):.3f}')
    res[name]=[int(x0),int(y0),S,nx,ny,[round(float(v),3) for v in c]]
with open(out,'w') as fo:
    fo.write('// GENERATED by snapshots/s05-fix1d-study/fitfield.py: coarse light fields [x0, y0, spacing, nx, ny, values],\n')
    fo.write('// least-squares fits (>= 40 px knots, smoothed) of the pre-grade light over each drawn region of the source rest frame.\n')
    fo.write(f'export const {NAME} = {{\n'+',\n'.join(f'  {k}: {json.dumps(v)}' for k,v in res.items())+'\n};\n')
