#!/usr/bin/env python3
# tonefit.py RAW_RENDER.png [--S=48] [--lam=1] [--sig=16] [--reset]: fit a smooth gain grid G (frame px, spacing S) so that
# blur(render * G) ~ blur(source) (both pre-grade, the rest frame TB), outside the laptop screen. Multiplies into the
# existing grid in src/shots/s05/drawn/tonegrid.js (iterative), writes it back. Control values only (low-frequency light).
import sys, re, json, numpy as np, cv2
from scipy.sparse import lil_matrix, csr_matrix, vstack
from scipy.sparse.linalg import lsqr
a=sys.argv; opt=lambda k,d: float([s for s in a if s.startswith(f'--{k}=')][0].split('=')[1]) if any(s.startswith(f'--{k}=') for s in a) else d
S=int(opt('S',48)); lam=opt('lam',1.0); sig=opt('sig',16); ref=[s for s in a if s.startswith('--ref=')]; ref=ref[0][6:] if ref else 'TB'
OUT='/Users/computer/rootline/apprentice-film/src/shots/s05/drawn/tonegrid.js'
H,W=946,2206
x0,y0=-S*3,-S*3; nx=int(np.ceil((W+6*S)/S))+1; ny=int(np.ceil((H+6*S)/S))+1
old=np.ones(nx*ny)
if '--reset' not in a:
    try:
        t=open(OUT).read(); m=re.search(r'TONE = (\{.*\});',t,re.S); d=json.loads(m.group(1))
        if d['S']==S and d['nx']==nx and d['ny']==ny: old=np.array(d['g'])
    except Exception as e: print('no old grid',e)
r=cv2.imread(a[1]).astype(np.float32).mean(2)/255
s=np.load(f'{ref}_u.npy').mean(2).astype(np.float32)
m=np.ones((H,W),np.uint8); cv2.fillPoly(m,[np.array([[315,246],[834,168],[898,519],[409,648]],np.int32)],0)
m=cv2.erode(m,np.ones((9,9),np.uint8))
rb=cv2.GaussianBlur(r*m,(0,0),sig); sb=cv2.GaussianBlur(s*m,(0,0),sig); mb=cv2.GaussianBlur(m.astype(np.float32),(0,0),sig)
ok=(mb>0.5)&(rb/np.maximum(mb,1e-3)>0.03)
ratio=np.clip(sb/np.maximum(rb,1e-4),0.4,2.5)
ys,xs=np.nonzero(ok); ys=ys[::7]; xs=xs[::7]; y=ratio[ys,xs]; wt=np.sqrt(rb[ys,xs]/np.maximum(mb[ys,xs],1e-3))
fx=(xs-x0)/S; fy=(ys-y0)/S; i0=np.floor(fx).astype(int); j0=np.floor(fy).astype(int); ax=fx-i0; ay=fy-j0
n=len(xs); A=lil_matrix((n,nx*ny))
for (di,dj,w) in [(0,0,(1-ax)*(1-ay)),(1,0,ax*(1-ay)),(0,1,(1-ax)*ay),(1,1,ax*ay)]: A[np.arange(n),(j0+dj)*nx+(i0+di)]=w*wt
L=lil_matrix((2*nx*ny,nx*ny)); k=0
for j in range(ny):
    for i in range(nx):
        if i+1<nx: L[k,j*nx+i]=-1; L[k,j*nx+i+1]=1; k+=1
        if j+1<ny: L[k,j*nx+i]=-1; L[k,(j+1)*nx+i]=1; k+=1
L=L[:k]
# prior toward 1 (weak) so unseen nodes stay neutral
P=lil_matrix((nx*ny,nx*ny)); P.setdiag(1)
M=vstack([csr_matrix(A),csr_matrix(L)*np.sqrt(lam*n/k),csr_matrix(P)*np.sqrt(0.02*n/(nx*ny))])
b=np.concatenate([y*wt,np.zeros(k),np.ones(nx*ny)*np.sqrt(0.02*n/(nx*ny))])
g=lsqr(M,b,atol=1e-9,btol=1e-9,iter_lim=8000)[0]
g=np.clip(g,0.5,2.2)
new=np.clip(old*g,0.4,2.5)
print('gain range %.2f..%.2f  mean %.3f'%(g.min(),g.max(),g.mean()))
open(OUT,'w').write('// GENERATED by snapshots/s05-fix1d-study/tonefit.py: a smooth light-correction gain grid (frame px, knots every S px,\n'
 '// bilinear), fitted so the drawing\'s blurred pre-grade light (sigma %d px) matches the source rest frame\'s outside the\n// laptop screen. Low-frequency control values only.\nexport const TONE = %s;\n'%(int(sig),json.dumps(dict(x0=x0,y0=y0,S=S,nx=nx,ny=ny,g=[round(float(v),3) for v in new]))))
