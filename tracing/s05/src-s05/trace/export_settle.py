#!/usr/bin/env python3
# ../data/settle.js from CACHE/settle_fields.json (settle_fit.py): per layer a grid of displacement vectors per settle frame
import json, os, frames
from export import enc
F = json.load(open(f'{frames.CACHE}/settle_fields.json'))
lines = ['// s05 camera-settle motion: GENERATED by trace/export_settle.py (measured with trace/settle_fit.py: per layer, DIS optical',
         '// flow of the settled frame into each source frame 23.12-23.52, reduced to a grid of displacement vectors).',
         '// FIELDS[layer] = { x0, y0, G (node spacing, px), nx, ny, d: one string per frame of KS } ; each string holds, node by',
         '// node (row-major), dx then dy in 0.1 px (settled position -> position in that frame), packed like ./room.js numbers.',
         f'export const KS = {json.dumps(F["ks"])};', 'export const FIELDS = {']
for L, g in F['layers'].items():
    ds = []
    for gdx, gdy in g['grids']:
        nums = []
        for j in range(g['ny']):
            for i in range(g['nx']): nums += [gdx[j][i], gdy[j][i]]
        ds.append(enc(nums))
    lines.append(f'  {L}: {{ x0: {g["x0"]}, y0: {g["y0"]}, G: {g["G"]}, nx: {g["nx"]}, ny: {g["ny"]}, d: {json.dumps(ds)} }},')
lines += ['};', '']
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'settle.js'); open(p, 'w').write('\n'.join(lines)); print(p, os.path.getsize(p))
