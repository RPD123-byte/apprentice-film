# silfill.py: small slits in the traced silhouettes (sil_data.js): the difference between a morphological closing of
# each drawing's silhouette mask and the mask itself, kept only for small components (slits, not the long gaps between
# primaries); written as extra polygons (page px) to src/shots/s17/sil_fill.js. Derived from our own traced data only.
import json, cv2, numpy as np, sys
S=open('../../src/shots/s17/sil_data.js').read(); SIL=json.loads(S[S.index('{'):S.rindex('}')+1])
K=int(sys.argv[1]) if len(sys.argv)>1 else 7; AMAX=float(sys.argv[2]) if len(sys.argv)>2 else 60
out={}; rep=[]
for k,polys in sorted(SIL.items()):
    sc=4
    m=np.zeros((946*sc//2,2206*sc//2),np.uint8)  # half-size canvas at 2x (region crop below)
    xs=[];ys=[]
    for q in polys: a=np.array(q).reshape(-1,2); xs+= list(a[:,0]); ys+=list(a[:,1])
    x0,y0=int(min(xs))-20,int(min(ys))-20; x1,y1=int(max(xs))+20,int(max(ys))+20
    W,H=(x1-x0)*sc,(y1-y0)*sc
    m=np.zeros((H,W),np.uint8)
    for q in polys:
        a=((np.array(q).reshape(-1,2)-[x0,y0])*sc).round().astype(np.int32); cv2.fillPoly(m,[a],255)
    ker=cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(K*sc|1,K*sc|1))
    c=cv2.morphologyEx(m,cv2.MORPH_CLOSE,ker)
    d=((c>0)&(m==0)).astype(np.uint8)*255
    n,lab,st,cen=cv2.connectedComponentsWithStats(d)
    polys_out=[]
    for i in range(1,n):
        area=st[i,cv2.CC_STAT_AREA]/(sc*sc)
        if area>AMAX or area<2: continue
        cx,cy=cen[i]/sc+[x0,y0]
        if not (float(k)>=51.1 and float(k)<52.5 and 686<=cx<=700 and 484<=cy<=518): continue
        comp=(lab==i).astype(np.uint8)*255
        comp=cv2.dilate(comp,np.ones((3,3),np.uint8))   # overlap the silhouette a little
        cs,_=cv2.findContours(comp,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
        for cc in cs:
            p=cc.reshape(-1,2)/sc+[x0,y0]
            if len(p)>=3: polys_out.append([round(float(v),1) for v in p.flatten()])
        rep.append((k,round(area,1),tuple(np.round(cen[i]/sc+[x0,y0],1))))
    if polys_out: out[k]=polys_out
open('../../src/shots/s17/sil_fill.js','w').write('// s17 slit fills (fix pass 1): small slits left by the tracer in each drawing\'s silhouette (sil_data.js), found as\n// the difference between a %d px closing of the silhouette and the silhouette itself, components up to %g px² at the wing–body junction (x 686–700, y 484–518, 51.12–52.44);\n// generated by snapshots/s17-fix1x-lab/silfill.py from our traced outlines only (no source pixels). Page px, flat [x0, y0, ...].\nexport const SIL_FILL = %s;\n'%(K,AMAX,json.dumps(out,separators=(',',':'))))
for r in rep: print(r)
print(len(rep),'components in',len(out),'drawings')
