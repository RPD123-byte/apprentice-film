# silfill_dash.py: the tracer's split lines and slits inside the dash owl's head (sil_data.js, 52.68–53.20): the
# difference between a K px closing of each drawing's silhouette mask and the mask itself, components within R px of
# the model head centre and up to AMAX px²; written as polygons (page px) to src/shots/s17/sil_fill_dash.js.
# Derived from our own traced outlines only (no source pixels).
import json, cv2, numpy as np, sys
S=open('../../src/shots/s17/sil_data.js').read(); SIL=json.loads(S[S.index('{'):S.rindex('}')+1])
HC=json.load(open('hout.json'))
K=int(sys.argv[1]) if len(sys.argv)>1 else 9; AMAX=float(sys.argv[2]) if len(sys.argv)>2 else 400; RR=float(sys.argv[3]) if len(sys.argv)>3 else 44
out={}; rep=[]
for k in sorted(HC):
    polys=SIL[k]; cx,cy=HC[k]['c']; sc=4
    x0,y0=int(cx-90),int(cy-90); W=H=180*sc
    m=np.zeros((H,W),np.uint8)
    for q in polys:
        a=((np.array(q).reshape(-1,2)-[x0,y0])*sc).round().astype(np.int32); cv2.fillPoly(m,[a],255)
    c=cv2.morphologyEx(m,cv2.MORPH_CLOSE,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(K*sc|1,K*sc|1)))
    d=((c>0)&(m==0)).astype(np.uint8)*255
    n,lab,st,cen=cv2.connectedComponentsWithStats(d)
    po=[]
    for i in range(1,n):
        area=st[i,cv2.CC_STAT_AREA]/(sc*sc); px,py=cen[i]/sc+[x0,y0]
        if area>AMAX or area<1.5 or np.hypot(px-cx,py-cy)>RR or py<cy-22: continue   # not the crown (the real gap under the band)
        comp=cv2.dilate((lab==i).astype(np.uint8)*255,np.ones((3,3),np.uint8))
        cs,_=cv2.findContours(comp,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
        for cc in cs:
            p=cc.reshape(-1,2)/sc+[x0,y0]
            if len(p)>=3: po.append([round(float(v),1) for v in p.flatten()])
        rep.append((k,round(area,1),round(px,1),round(py,1)))
    if po: out[k]=po
open('../../src/shots/s17/sil_fill_dash.js','w').write("// s17 dash-head fills (fix pass 2): the tracer's split lines and slits inside the dash owl's head (sil_data.js,\n// 52.68–53.20; e.g. 53.08 down the face at x ~471 to the bill), found as the difference between a %d px closing of the\n// drawing's silhouette and the silhouette itself, components within %g px of the head centre and below its crown (y > centre - 22), up to %g px²; generated by\n// snapshots/s17-fix2-lab/silfill_dash.py from our traced outlines only (no source pixels). Page px, flat [x0, y0, ...].\nexport const SIL_FILL_DASH = %s;\n"%(K,RR,AMAX,json.dumps(out,separators=(',',':'))))
for r in rep: print(r)
