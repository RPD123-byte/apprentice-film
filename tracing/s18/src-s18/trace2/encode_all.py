#!/usr/bin/env python3
# encode_all.py WORKDIR - write ../data/*.js from the traced drawings (pickles in WORKDIR)
import sys, os, json, pickle
sys.path.insert(0, os.path.dirname(__file__))
from tojs import drawing_js, write_module
W = sys.argv[1]; DATA = os.path.join(os.path.dirname(__file__), '..', 'data')
H = '// Generated by src/shots/s18/trace2/encode_all.py - '
what = sys.argv[2].split(',') if len(sys.argv) > 2 else ['roomA', 'bgB', 'kbB', 'owlA', 'owlB']
if 'roomA' in what:
    print('roomA', write_module(f'{DATA}/roomA.js', 'ROOM_A', drawing_js(pickle.load(open(f'{W}/A3.pkl', 'rb'))),
          H + 'shot A plate as an ink drawing (trace_plate2.py on the owl-free plate). Measured shapes and centre-lines only.'))
if 'bgB' in what:
    print('bgB', write_module(f'{DATA}/bgB.js', 'BG_B', drawing_js(pickle.load(open(f'{W}/BGB.pkl', 'rb'))),
          H + 'shot B background (never moves), frame px (plateB2.py + trace_plate2.py). Measured shapes and centre-lines only.'))
if 'kbB' in what:
    print('kbB', write_module(f'{DATA}/kbB.js', 'KB_B', drawing_js(pickle.load(open(f'{W}/KBB.pkl', 'rb'))),
          H + 'shot B keyboard in its canvas coords (plate x + 260; the tip transform moves it). Measured shapes and centre-lines only.'))
if 'owlA' in what:
    D = pickle.load(open(f'{W}/owlA.pkl', 'rb'))
    o = {'phase': {k: drawing_js(v) for k, v in D['phase'].items()}, 'feet': {str(n): drawing_js(v) for n, v in D['feet'].items()}}
    print('owlA', write_module(f'{DATA}/owlA.js', 'OWL_A', o, H + 'shot A owl: one rigid drawing per wing phase and the legs / feet per\n// frame (trace_owlA2.py), frame px at the frame-1356 placement (PATH_A moves them). Measured shapes, value fields and centre-lines only.'))
if 'owlB' in what:
    R = pickle.load(open(f'{W}/owlB.pkl', 'rb'))
    tA = {int(k): v for k, v in R['tailA'].items()}
    if os.path.exists(f'{W}/tailA_refit.json'):
        for k, v in json.load(open(f'{W}/tailA_refit.json')).items(): tA[int(k)] = v
        if 1400 in tA: tA[1401] = tA[1400]
    o = {'belly': drawing_js(R['belly']), 'tail': drawing_js(R['tail']), 'wing': {k: (drawing_js(v) if v else None) for k, v in R['wing'].items()},
         'state': {str(k): v for k, v in R['state'].items()}, 'tailA': {str(k): [[round(x, 5) for x in r] for r in v] for k, v in tA.items()},
         'parts': {str(n): drawing_js(v) for n, v in R['parts'].items()}, 'keys': {str(n): drawing_js(v) for n, v in R['keys'].items()},
         'fly': {str(n): drawing_js(v) for n, v in R['fly'].items()}}
    KJ = f'{W}/keys3.json'
    if os.path.exists(KJ):
        # pressed keys (measure_keys.py): wedges = polygon, line angle, pitch, offset, width, dark / paper tones;
        # front lines = segment end points, width, tone
        K = json.load(open(KJ))
        o['bands'] = {k: [[it['poly'], it['ang'], it['per'], it['off'], it['w'], round(it['dark'] * 255), round(it['paper'] * 255)] for it in v]
                      for k, v in K.items() if k != 'lines' and v}
        o['klines'] = {k: [s_[:5] + [round(s_[5] * 255)] for s_ in v] for k, v in K['lines'].items() if v}
    print('owlB', write_module(f'{DATA}/owlB.js', 'OWL_B', o, H + 'shot B owl (trace_owlB2.py): rigid belly (traced on frame 1382) and\n// far wing (registered coords, TRACK_B), tail (1382 placement, per-frame affine, refit_tail.py), per-frame legs / feet / near\n// wing (parts), pressed-key marks next to them (keys), the leaping owl (fly). Measured shapes, value fields and centre-lines only.'))
