# Which traced key drawing draws the owl on each frame, and where (measurement script): reads the ECC fits
# (owlkeys.py fit -> snapshots/s20-f2-trace/fits_<key>.json) and writes src/shots/s20/data/owlframes.js.
# RANGES: key -> frame numbers it may cover; a frame takes the best-fitting allowed key if its cc >= MIN_CC,
# otherwise the rig draws it. OVERRIDE forces a choice (measured against the rig on the render, see fidelity/s20.md).
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import composite2 as C
OUT = C.OUT
RANGES = {
    'rear': range(1578, 1592), 'front': range(1592, 1608),
    'flap0': range(1608, 1641), 'flap1': range(1608, 1641), 'flap2': range(1608, 1641), 'flap3': range(1608, 1641),
    'stare1': range(1640, 1665), 'stare2': range(1664, 1680),
}
# measured on the render (owl-band blurred MAE, key vs rig): the rig wins on 64.40 and 65.64, the keys everywhere else
MIN_CC = float(os.environ.get('MIN_CC', '0.5'))
EXCLUDE = set(int(v) for v in os.environ.get('EXCLUDE', '1610,1641').split(',') if v)
best = {}
for k, rg in RANGES.items():
    p = OUT + '/fits_%s.json' % k
    if not os.path.exists(p): continue
    for t, w in json.load(open(p)).items():
        n = int(round(float(t) * 25))
        if n not in rg or n in EXCLUDE: continue
        if w[6] >= MIN_CC and (n not in best or w[6] > best[n][1][6]): best[n] = (k, w)
# single-frame traces (owlkeys.py frame): drawn in screen coordinates, they replace key / rig / props on their frame
SCREEN = json.load(open(OUT + '/screen_frames.json')) if os.path.exists(OUT + '/screen_frames.json') else {}
SKIP_SCREEN = set(os.environ.get('SKIP_SCREEN', '').split(','))
for t, name in SCREEN.items():
    if t in SKIP_SCREEN: continue
    if isinstance(name, list): best[int(round(float(t) * 25))] = (name[0], [1, 0, 0, 1, 0, 0, 1.0, 'screen', name[1]])
    else: best[int(round(float(t) * 25))] = (name, [1, 0, 0, 1, 0, 0, 1.0, 'screen'])
# haze layers (owlkeys.py haze): drawn under the held stare key on their frames
HZ = json.load(open(OUT + '/haze_frames.json')) if os.path.exists(OUT + '/haze_frames.json') else {}
hz = ["// Haze layers per frame (generated by s20/trace/select_frames.py): time -> traced haze data (A frame px)."]
for t, name in sorted(HZ.items()): hz.append('import { %s } from "./%s.js";' % (name.upper(), name))
hz.append("export const HAZE_LAYERS = { " + ", ".join('"%s": %s' % (t, name.upper()) for t, name in sorted(HZ.items())) + " };")
open(os.path.join(os.path.dirname(__file__), '..', 'data', 'haze_index.js'), 'w').write('\n'.join(hz) + '\n')
used = sorted(set(k for k, w in best.values()))
idx = ["// Traced owl drawings used by s20 (generated by s20/trace/select_frames.py)."]
for k in used: idx.append('import { OWL_%s } from "./owl_%s.js";' % (k.upper(), k))
idx.append("export const KEYDATA = { " + ", ".join('%s: OWL_%s' % (k, k.upper()) for k in used) + " };")
open(os.path.join(os.path.dirname(__file__), '..', 'data', 'owlkeys_index.js'), 'w').write('\n'.join(idx) + '\n')
lines = ["// Owl key drawing per frame (s20/trace/select_frames.py from the ECC fits): time -> [key, a, b, c, d, e, f, cc];",
         "// the key canvas (setup-A frame px) is drawn through transform(a, b, c, d, e, f). Frames not listed use the rig.",
         "export const OWL_FRAMES = {"]
for n in sorted(best):
    k, w = best[n]
    lines.append('  "%.2f": ["%s", %s],' % (n / 25, k, ', '.join(('"%s"' % v) if isinstance(v, str) else ('%g' % v) for v in w)))
lines.append("};")
open(os.path.join(os.path.dirname(__file__), '..', 'data', 'owlframes.js'), 'w').write('\n'.join(lines) + '\n')
print(len(best), 'frames', ' '.join('%.2f:%s:%.2f' % (n / 25, best[n][0], best[n][1][6]) for n in sorted(best)))
