# Synthetic filler bars for the speed-line sets A, B, C: drop the stub clusters / fat capsules left where the F owl was
# masked out when the sets were measured, then add seeded bars (angle of the set, widths/values/lengths sampled from
# the set's own long bars, lengths from the measured distribution) wherever the line density falls well below the
# frame's median. Output: src/shots/s24/d/lineFill.js (drop indices + synthetic bars; no source pixels).
import json,cv2,numpy as np,math
# sets.json = LINE_SETS exported from src/shots/s24/d/lineData.js, e.g.
#   node -e "import('./src/shots/s24/d/lineData.js').then(m=>require('fs').writeFileSync('sets.json',JSON.stringify(m.LINE_SETS)))"
# run from the project root:  python3 snapshots/s24d-h/tools/linefill.py 0.4
S=json.load(open('sets.json'))
W,H=2206,946
import sys
TARGET=float(sys.argv[1]) if len(sys.argv)>1 else 0.6
rng=np.random.default_rng(2424)
out={'DROP':{},'FILL':{}}
def raster(bars,ang):
  a=math.radians(ang); c,s=math.cos(a),math.sin(a)
  im=np.zeros((H,W),np.uint8)
  for u0,u1,v,w,*_ in bars:
    p0=(u0*c-v*s,u0*s+v*c); p1=(u1*c-v*s,u1*s+v*c)
    cv2.line(im,(int(round(p0[0])),int(round(p0[1]))),(int(round(p1[0])),int(round(p1[1]))),255,max(1,int(round(w))))
  return im
for n in ['A','B','C']:
  st=S[n]; ang=st['ang']; a=math.radians(ang); c,s=math.cos(a),math.sin(a)
  bars=[list(b) for b in st['bars']]
  drop=[]
  for i,b in enumerate(bars):
    u0,u1,v,w=b[:4]; L=u1-u0; mu=(u0+u1)/2; x=mu*c-v*s; y=mu*s+v*c
    if (L<60 and 1300<=x<=1850 and 350<=y<=850) or (w>14 and x>1100 and y>150) or (L<150 and 1540<=x<=1820 and 640<=y<=920) or L<16: drop.append(i)
  keep=[b for i,b in enumerate(bars) if i not in drop]
  longb=[b for b in keep if b[1]-b[0]>150]
  occ=raster(keep,ang)
  def dens(o): return cv2.blur((o>0).astype(np.float32),(151,151))
  d=dens(occ); med=float(np.median(d[75:-75,75:-75]))
  fill=[]
  for it in range(1500):
    d=dens(occ)
    dd=d.copy(); dd[:40,:]=9; dd[-40:,:]=9; dd[:,:40]=9; dd[:,-40:]=9
    y,x=np.unravel_index(np.argmin(dd),dd.shape)
    if dd[y,x]>=TARGET*med: break
    # a new bar through (x, y)
    u=x*c+y*s; v=-x*s+y*c + rng.uniform(-8,8)
    L=float(np.exp(rng.normal(math.log(293),0.85))); L=min(max(L,90),900)
    t=rng.uniform(0.25,0.75); u0=u-L*t; u1=u0+L
    src=longb[rng.integers(len(longb))]; w=src[3]; vals=src[4:7]
    # keep clear of existing bars in the same lane
    ok=False
    for dv in [0,6,-6,12,-12,18,-18,26,-26]:
      vv=v+dv
      if all(not (abs(b[2]-vv)<(b[3]+w)/2+3 and not (b[1]<u0-10 or b[0]>u1+10)) for b in keep+fill): ok=True; v=vv; break
    if not ok:
      cv2.circle(occ,(int(x),int(y)),14,1,-1)  # mark so we move on
      continue
    fill.append([round(u0),round(u1),round(v,2),w]+list(vals))
    p0=(u0*c-v*s,u0*s+v*c); p1=(u1*c-v*s,u1*s+v*c)
    cv2.line(occ,(int(p0[0]),int(p0[1])),(int(p1[0]),int(p1[1])),255,max(1,int(round(w))))
  out['DROP'][n]=drop; out['FILL'][n]=fill
  print(n,'drop',len(drop),'fill',len(fill),'median density %.3f'%med,'min after %.3f'%dens(occ)[40:-40,40:-40].min())
js='''// s24 speed lines, fix pass 1: repairs to the measured sets A, B, C (lineData.js). DROP = indices of the stub
// clusters / fat capsules left where the F owl was masked out when the sets were measured; FILL = synthetic bars
// (seeded: the set's angle, widths and values sampled from its own long bars, lengths from the measured distribution,
// median 293 px) added wherever the line density fell below %s× the frame median. Generated by
// snapshots/s24d-h/tools/linefill.py. Same format as lineData.js: [u0, u1, v, width, value start / middle / end].
export const DROP = %s;
export const FILL = %s;
''' % (TARGET, json.dumps(out["DROP"]), json.dumps(out["FILL"]))
open('src/shots/s24/d/lineFill.js','w').write(js)
