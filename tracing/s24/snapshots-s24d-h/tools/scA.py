def pair(d):
  # pair each tip with the hole on the far side of the pivot (the X of a pair of scissors)
  P=d['P']; T=d['T']; H=d['H']
  def ang(a,b): 
    va=(a[0]-P[0],a[1]-P[1]); vb=(b[0]-P[0],b[1]-P[1])
    c=(va[0]*vb[0]+va[1]*vb[1])/(math.hypot(*va)*math.hypot(*vb)+1e-9); return c
  s0=ang(T[0],H[0])+ang(T[1],H[1]); s1=ang(T[0],H[1])+ang(T[1],H[0])
  return [(T[0],H[0]),(T[1],H[1])] if s0<s1 else [(T[0],H[1]),(T[1],H[0])]
