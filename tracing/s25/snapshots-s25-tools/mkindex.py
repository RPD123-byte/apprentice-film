#!/usr/bin/env python3
# mkindex.py -- write src/shots/s25/v2/drawings.js importing every data/*.js drawing into one DRAW map
import os, glob
HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, '..', '..', 'src', 'shots', 's25', 'v2')
names = sorted(os.path.basename(p)[:-3] for p in glob.glob(os.path.join(D, 'data', '*.js')))
names = [n for n in names if n not in ('head',)]
js = "// s25 v2 — every measured drawing by key (generated by snapshots/s25-tools/mkindex.py)\n"
for n in names: js += f'import {{ D_{n.upper()} }} from "./data/{n}.js";\n'
js += "export const DRAW = {\n" + "".join(f"  {n}: D_{n.upper()},\n" for n in names) + "};\n"
open(os.path.join(D, 'drawings.js'), 'w').write(js)
print(len(names), 'drawings:', ' '.join(names))
