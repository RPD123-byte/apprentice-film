# end-s27-tfix: room_vec output (plain int lists) -> codec-encoded key file in src/shots/s27/okeys/ + index.js
import sys, os, json, re; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tio import enc, load_js
SRC = '/Users/computer/rootline/apprentice-film/src/shots/s27/okeys'
WORK = '/Users/computer/rootline/apprentice-film/snapshots/end-s27-tfix-work'
os.makedirs(SRC, exist_ok=True)
def deep(x):
    if isinstance(x, list) and x and all(isinstance(v, int) for v in x) and len(x) >= 4: return enc(x)
    if isinstance(x, list): return [deep(v) for v in x]
    return x
FS = list(map(int, sys.argv[1].split(',')))
imp = []; ent = []
for F in FS:
    t = '%.2f' % (F / 25); n = t.replace('.', '_')
    d = load_js(f'{WORK}/tr/o_{n}.js'); R = d[f'O{n}_REGIONS']; I = d[f'O{n}_INK']
    js = (f"// s27 end-orbit room key at frame {F} ({t} s), end-s27-tfix: traced from the source (plate: frames {F-2}..{min(F+2,3232)} brought onto\n"
          f"// this frame by the room mesh + a small dense refinement, per-pixel median, light NLM; un-graded), foreground objects cut out and\n"
          f"// filled. Ink = ridge filter (sato) + hysteresis. Frame px x2, codec strings (codec.js). Generated by\n"
          f"// snapshots/end-s27-tfix-tools/keys.sh (plate.py, keymask2.py, room_vec.py) and export.py; painted by room.js paintTrace.\n"
          f"export const O{n}_REGIONS = " + json.dumps(deep(R), separators=(',', ':')) + ";\n"
          f"export const O{n}_INK = " + json.dumps(deep(I), separators=(',', ':')) + ";\n")
    open(f'{SRC}/o_{n}.js', 'w').write(js)
    imp.append(f'import {{ O{n}_REGIONS as R{F}, O{n}_INK as I{F} }} from "./o_{n}.js";'); ent.append(f'[{F}, R{F}, I{F}]')
    print(F, os.path.getsize(f'{SRC}/o_{n}.js'))
idx = ("// s27 end-orbit room keys (end-s27-tfix): one traced view every 3 source frames from 127.88 to 129.28, each drawn through the\n"
       "// per-frame room mesh (orbitMesh.js) onto the frames next to it. [frame index at 25 fps, REGIONS, INK]\n" + "\n".join(imp) +
       "\nexport const OKEYS = [" + ", ".join(ent) + "];\n")
open(f'{SRC}/index.js', 'w').write(idx)
