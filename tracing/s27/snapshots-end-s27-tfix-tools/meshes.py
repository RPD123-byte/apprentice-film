# end-s27-tfix: per-frame room meshes for the end orbit -> src/shots/s27/orbitMesh.js (numbers only).
# For every frame F between two room keys Ka < F < Kb: where each node of a regular GS-px grid of frame F lies in key frame
# Ka and in Kb (flowmesh.fit on the source, background only). Stored as node displacements in 1/4 px, codec strings.
# Usage: FM_GS=32 python3 meshes.py OUT.js K1,K2,...
import sys, os, json; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from flowmesh import *
from tio import enc
OUT = sys.argv[1]; KS = list(map(int, sys.argv[2].split(',')))
rows = {}
err = {}
for i in range(len(KS) - 1):
    a, b = KS[i], KS[i + 1]
    for F in range(a + 1, b):
        r = []
        for K in (a, b):
            m, info = fit(F, K, 0.0003, 0.003)
            q = np.round(m * 4).astype(int).reshape(-1).tolist()
            r.append([K, enc(q)])
        rows[F] = r
        print(F, 'keys', a, b, flush=True)
hdr = f"""// s27 end orbit (end-s27-tfix): per-frame room meshes. For frame F (25 fps index) between room keys Ka < F < Kb, where
// each node of a regular grid of the frame (x = X0 + i*GS, y = Y0 + j*GS, NX x NY, row-major) lies in key frame Ka and in
// Kb: the displacement (dx, dy) in 1/4 px, flattened [dx0, dy0, dx1, dy1, ...] and stored as codec strings (codec.js).
// Measured on the source (dense DIS flow on the room only, forward-backward checked, least-squares mesh); generated by
// snapshots/end-s27-tfix-tools/meshes.py.
"""
js = hdr + f"export const OM_GRID = {{ GS: {GS}, NX: {NX}, NY: {NY}, X0: {int(GXS[0])}, Y0: {int(GYS[0])} }};\n"
js += "export const OM_KEYS = " + json.dumps(KS) + ";\n"
js += "export const OM = {\n" + ",\n".join(f"  {F}: " + json.dumps(r, separators=(',', ':')) for F, r in sorted(rows.items())) + "\n};\n"
open(OUT, 'w').write(js)
print('bytes', os.path.getsize(OUT))
