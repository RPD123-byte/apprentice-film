# Export the measured s27 tracks (snapshots/s27d-meas/*.json) to src/shots/s27/drawn/tracks.js.
# Each track: rows [t, h11,h12,h13,h21,h22,h23,h31,h32] (h33 = 1), one per source frame (0.04 s).
import json, os, numpy as np
M='../s27d-meas/'
def load(fn, key='H'):
    J=json.load(open(M+fn)); R=J[key] if isinstance(J,dict) else J
    out={}
    for r in R:
        H=np.array(r[1:]).reshape(3,3); H=H/H[2,2]; out[round(r[0],2)]=H
    return out
def rows(d,t0=None,t1=None):
    ks=sorted(k for k in d if (t0 is None or k>=t0-1e-6) and (t1 is None or k<=t1+1e-6))
    def f(v,sig):
        s=f"{v:.{sig}g}"; return s
    out=[]
    for k in ks:
        H=d[k].flatten()
        vals=[f"{k:.2f}"]+[f"{H[0]:.6g}",f"{H[1]:.6g}",f"{H[2]:.7g}",f"{H[3]:.6g}",f"{H[4]:.6g}",f"{H[5]:.7g}",f"{H[6]:.5g}",f"{H[7]:.5g}"]
        out.append("["+",".join(vals)+"]")
    return "[\n"+",\n".join(out)+"]"
S=load('screen.json',None); S2=load('screen2.json',None)
for k,v in S2.items():
    if k>=122.0: S[k]=v
S={k:v for k,v in S.items() if k>=117.92 and k<=128.36}
parts=[]
parts.append("// s27 (drawn) measured tracks — generated by snapshots/s27d-tools/export_tracks.py from the source film; do not edit.\n"
 "// Positions only (homographies of planes), no appearance. Rows: [t, h11,h12,h13,h21,h22,h23,h31,h32] (h33 = 1).\n")
parts.append("// SCREEN: colour page px -> frame px (SIFT against the page at identity, then chained), 117.92-128.36\nexport const SCREEN = "+rows(S)+";\n")
for name,fn,desc in [('BASE','klt_base.json','laptop base top face: frame px at 119.6 -> frame px at t (KLT)'),
                     ('WALL','bg_full.json','back wall: frame px at 119.6 -> frame px at t (masked KLT, one homography)'),
                     ('MUG','klt_mug.json','mug (affine): frame px at 119.6 -> t'),
                     ('NOTEBOOK','klt_notebook.json','notebook: frame px at 119.6 -> t')]:
    if not os.path.exists(M+fn): continue
    parts.append(f"// {name}: {desc}\nexport const {name} = "+rows(load(fn))+";\n")
open('../../src/shots/s27/drawn/tracks.js','w').write("\n".join(parts))
print('ok', len(S))
