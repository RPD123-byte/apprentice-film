# export the new s27 tracks into src/shots/s27/data3.js
import json
D='/Users/computer/rootline/apprentice-film/snapshots/s27-k-trace/'
fr={}
for f in ['des_back.json','des_fwd.json']: fr.update(json.load(open(D+f))['frames'])
ch=json.load(open(D+'des_chain.json'))['frames']; pr=json.load(open(D+'des_pairs.json'))['frames']
for t,P in ch.items():
    if 127.6<float(t)<127.88: fr[t]=P
for t,P in pr.items(): fr[t]=P
rows=[[float(t)]+[round(v,1) for p in P for v in p] for t,P in sorted(fr.items(),key=lambda kv: float(kv[0])) if float(t)>=121.6-1e-6]
out=["// s27 measured tracks, part 3 (generated by snapshots/s27-k-tools/export3.py from the source film).",
"// DES_MESH: [t, x0,y0, ...] the designer's 12x9 control mesh (frame@125 grid -> frame@t), 121.6-129.28 every frame, tracked",
"// by template alignment on the source (des_track.py: DIS flow of the mesh-warped 125.0 frame against each frame, a robust",
"// affine plus a damped non-rigid residual, no folds), chained backward and forward from 125.0; after 127.6 chained by the",
"// designer's own source flow (flow_chain.py) and refined key to key (pair_refine.py) so the traced end views line up.",
"export const DES_MESH = "+json.dumps(rows,separators=(',',':'))+";"]
open('/Users/computer/rootline/apprentice-film/src/shots/s27/data3.js','w').write("\n".join(out)+"\n")
print(len(rows))
