# Writes src/shots/s27/data.js from the measurement JSONs (all numbers measured on the source film).
import json, numpy as np
R=lambda v,n=2: [round(float(x),n) for x in v]
out=[]
out.append("// s27 measured tracks (generated by snapshots/s27-meas/export_data.py from the source film; do not edit by hand).")
# screen: page->frame homography, film time
d=json.load(open('screenT_118.0_129.3.json'))
rows=[]
for t in sorted(d,key=float):
    if float(t)>128.44: continue
    H=np.array(d[t]['H']); H=H/H[2,2]
    rows.append([round(float(t),2)]+[round(float(x),7 if i in (6,7) else 5) for i,x in enumerate(H.ravel())])
out.append("// SCREEN: [t, h11..h33] page px (2206x946 colour page) -> frame px. SIFT homography, tracked frame to frame.")
out.append("export const SCREEN = "+json.dumps(rows,separators=(',',':'))+";")
# base corners
b=json.load(open('base_seq2.json'))
rows=[[round(float(t),2)]+R(v,1) for t,v in sorted(b['corners'].items(),key=lambda kv:float(kv[0]))]
out.append("// BASE: [t, FLx,FLy, FRx,FRy, BRx,BRy, BLx,BLy] top-face corners of the laptop base (texture W=32.4 x D=22.5 cm), chamfer-fitted.")
out.append("export const BASE = "+json.dumps(rows,separators=(',',':'))+";")
# background homography A (119.6 -> t)
g=json.load(open('bgH.json'))
rows=[]
for t in sorted(g,key=float):
    if float(t)>126.6: continue
    H=np.array(g[t]); H=H/H[2,2]
    rows.append([round(float(t),2)]+[round(float(x),8 if i in (6,7) else 5) for i,x in enumerate(H.ravel())])
out.append("// BG: [t, h..] wall/shelf homography, frame@119.6 -> frame@t (SIFT, chained). Held after 126.6 until 127.6.")
out.append("export const BG = "+json.dumps(rows,separators=(',',':'))+";")
a=json.load(open('bg_end_aff.json'))
rows=[[round(float(t),2)]+[round(float(x),5) for x in np.array(M).ravel()] for t,M in sorted(a.items(),key=lambda kv:float(kv[0]))]
out.append("// BG_END: [t, a,b,c,d,e,f] affine of the upper background, frame@127.6 -> frame@t (LK, 111-363 points).")
out.append("export const BG_END = "+json.dumps(rows,separators=(',',':'))+";")
nb=json.load(open('nb_top.json'))
rows=[[round(float(t),2)]+R(v,1) for t,v in sorted(nb.items(),key=lambda kv:float(kv[0]))]
out.append("// NOTEBOOK: [t, 4 corners (back-left, back-right, front-right, front-left)] top face, chamfer-fitted.")
out.append("export const NOTEBOOK = "+json.dumps(rows,separators=(',',':'))+";")
dc=json.load(open('des_ctrl.json'))
G=dc['grid']; fr=dc['frames']
ts=sorted(fr,key=float)
rows=[[round(float(t),2)]+R(np.array(fr[t]).ravel(),1) for t in ts if round(float(t)*25)%2==0 or float(t)>=127.6]
out.append("// DESIGNER: control grid (125.0 frame coords) and its positions per time (local-affine LK motion field).")
out.append("export const DES_GRID = "+json.dumps(G,separators=(',',':'))+";")
out.append("export const DES = "+json.dumps(rows,separators=(',',':'))+";")
open('/Users/computer/rootline/apprentice-film/src/shots/s27/data.js','w').write("\n".join(out)+"\n")
