# end-s28-fix1: the bedside cabinet and wall right of his shoulder (x 1440-1690, y 420-750). The room keys never saw the
# cabinet's left part (behind him), and the figure keys' hand-over smeared a pale blob / ghost contour over it at
# 130.96-131.40. One trace per source frame 130.96-131.40 (drawn over the figure pass), and one static trace of the locked
# view from the median of 23 locked frames (drawn under the figure pass, so his breathing edge stays his own).
# Clip: the room part of the box (ink-bounded flood from the right, cabseg2.py), faded out along the box's top, right and
# bottom edges. -> src/shots/s28/cabpatch.js
import sys, numpy as np, cv2
sys.path.insert(0, '/Users/computer/rootline/apprentice-film/snapshots/end-s28-fix1-tools')
from tp import trace, write_module, median_pre
import cabseg2
from cabseg2 import X0, Y0, X1, Y1
FADE = [['t', Y0, 16], ['r', X1, 20], ['b', Y1, 16]]
items = []
def full(room):
    m = np.zeros((946, 2206), np.uint8); m[Y0:Y1, X0:X1] = room; return m
for n in range(3274, 3286):
    crop, room = cabseg2.seg(n)
    D = trace(f'cab{n}', n / 25, full(room), pad=5, clip_dilate=2)
    D['t'] = round(n / 25, 2); D['fade'] = FADE; D['over'] = 1
    items.append(D); print(n, len(D['regions']), 'regions', len(D['ink']), 'ink', flush=True)
ts = [round(132.04 + 0.16 * i, 2) for i in range(23)]
img = median_pre(ts)
# the median pre-grade image, back to 8-bit graded-ish for the segmentation's thresholds: segment the median SOURCE frame
src = np.median(np.stack([cv2.imread(f'{cabseg2.SP}/src/{int(round(t * 25))}.png') for t in ts]), 0).astype(np.uint8)
crop, room = cabseg2.seg_img(src)
D = trace('cablock', 133.6, full(room), pad=5, clip_dilate=2, img=img)
D['t'] = 131.44; D['fade'] = FADE; D['over'] = 0; D['lock'] = 1
items.append(D); print('lock', len(D['regions']), 'regions', len(D['ink']), 'ink')
write_module('src/shots/s28/cabpatch.js', 'CABPATCH', items,
    "// Generated by snapshots/end-s28-fix1-tools/trace_cab.py. The bedside cabinet and wall right of his shoulder (x 1440-1690,\n"
    "// y 420-750): one vector trace per source frame 130.96-131.40 (drawn over the figure pass), and a static one of the\n"
    "// locked view from the median of 23 locked source frames (lock: 1, drawn under the figure pass), each cut to the room\n"
    "// part of the box and faded out along the box's top, right and bottom edges.\n")
