# end-s28-fix1: the strip just outside the laptop lid's LEFT edge in the locked view (bookshelf, pink box, cable): every
# room key hides it (behind the lid) and filled it with stretched colour, a pale halo along the edge. One static trace
# of the band from 10 px inside the lid's left edge to 40 px outside it, y 495-946, from the median of 23 locked source
# frames (132.04-135.56, the camera does not move and nothing moves there), drawn after the room, under the lid.
import sys, numpy as np, cv2, json
sys.path.insert(0, '/Users/computer/rootline/apprentice-film/snapshots/end-s28-fix1-tools')
from tp import trace, write_module, median_pre
TL = np.array([114.4, 505.7]); BL = np.array([207.0, 960.0])
d = (BL - TL) / np.linalg.norm(BL - TL); nrm = np.array([-d[1], d[0]])          # left (outward) normal: (-0.98, 0.2)
if nrm[0] > 0: nrm = -nrm
ys, xs = np.mgrid[0:946, 0:2206]
so = (xs - TL[0]) * nrm[0] + (ys - TL[1]) * nrm[1]                             # signed distance, + outside (left)
m = ((so >= -10) & (so <= 40) & (ys >= 495)).astype(np.uint8)
ts = [round(132.04 + 0.16 * i, 2) for i in range(23)]
img = median_pre(ts)
D = trace('lidstrip', 133.6, m, pad=4, clip_dilate=0, img=img)
D['t'] = 131.36
print(len(D['regions']), 'regions', len(D['ink']), 'ink')
write_module('src/shots/s28/lidstrip.js', 'LIDSTRIP', D,
    "// Generated by snapshots/end-s28-fix1-tools/trace_lidstrip.py. The locked view's strip just outside the laptop lid's left\n"
    "// edge (bookshelf, pink box, cable), which every room key hides behind the lid: one static vector trace (colour regions +\n"
    "// ink in three levels) of the median of 23 locked source frames, drawn after the room pass, under the lid.\n")
