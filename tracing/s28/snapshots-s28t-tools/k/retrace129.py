# Re-trace the first keys (129.32): the figure key now includes the owl peeking out beside the lid (the first build left it
# out of both layers), and the room key no longer hides that area.
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film')
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k'
Q = json.load(open(f'{T}/lidquads.json'))
SO = json.load(open(f'{T}/silh_orbit_out.json'))
def lidpoly(t, pad=4):
    q = Q[f"{min(t, 131.40):.2f}"]
    return [[q[0][0]-pad, q[0][1]-pad], [q[1][0]+pad, q[1][1]-pad], [q[2][0]+pad, q[2][1]+80], [q[3][0]-pad, q[3][1]+80]]
def ringmask(rings):
    m = np.zeros((946+400, 2206+400), np.uint8)
    for rr in rings: cv2.fillPoly(m, [np.int32(np.array(rr)+200)], 255)
    return m
def ring_of(m):
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    c = max(cs, key=cv2.contourArea).reshape(-1, 2)-200
    return cv2.approxPolyDP(c.reshape(-1, 1, 2).astype(np.float32), 1.0, True).reshape(-1, 2).tolist()
OWL = [[1250, 505], [1300, 498], [1330, 515], [1268, 730], [1232, 722], [1218, 650], [1220, 585], [1232, 535]]
t = 129.32
sil = SO[f"{t:.2f}"]
m = ringmask([sil] if not isinstance(sil[0][0], list) else sil)
m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5)))
cv2.fillPoly(m, [np.int32(np.array(OWL)+200)], 255)
# the beanie's top-left (the automatic silhouette cut through its knit band there)
BEANIE = [[848, 250], [860, 214], [892, 190], [930, 170], [970, 150], [1006, 135], [1044, 120], [1048, 136], [986, 180], [930, 206], [902, 248]]
cv2.fillPoly(m, [np.int32(np.array(BEANIE)+200)], 255)
area = ring_of(m)
def run(spec, name):
    sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
    return json.load(open(out))
def write(name, D, nd):
    for key in ('regions', 'ink'):
        for R in D.get(key, []):
            R['r'] = [[[round(x, nd) if nd else int(round(x)), round(y, nd) if nd else int(round(y))] for x, y in ring] for ring in R['r']]
    s = json.dumps(D, separators=(',', ':'))
    open(f'src/shots/s28/keys/{name}.js', 'w').write("// Generated by snapshots/s28t-tools/k/retrace129.py (vector trace of measured outlines and colours).\nexport default " + s + ";\n")
    print(name, len(s)//1024, 'KB', flush=True)
if 'fig' in sys.argv[1:]:
    D = run({"t": t, "area": [area], "exclude": [lidpoly(t, 5)], "fill_hidden": [], "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
             "ink": [{"lmax": 0.50, "contrast": 0.18, "eps": 0.7, "min_area": 4}, {"lmax": 0.24, "eps": 0.6, "min_area": 3}]}, "fig12932")
    D['sil'] = [area]; D['lid'] = Q[f"{t:.2f}"]
    write('fig12932', D, 1)
if 'room' in sys.argv[1:]:
    m2 = ringmask([sil] if not isinstance(sil[0][0], list) else sil)
    m2 = cv2.dilate(m2, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (11, 11)))   # 5 px (the first build: 12)
    hide = [ring_of(m2), lidpoly(t, 6)]
    D = run({"t": t, "area": [[[0, 0], [2206, 0], [2206, 946], [0, 946]]], "exclude": [], "fill_hidden": hide, "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
             "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.9, "min_area": 6}, {"lmax": 0.28, "eps": 0.8, "min_area": 4}]}, "room12932")
    D['hide'] = hide; D['base'] = '#e9dcc0'
    write('room12932', D, 0)
