# s28t: re-trace the orbit figure keys inside the refined silhouettes (sil_new.json), with the build's own settings
# (buildkeys.py): vector trace of the source frame -> src/shots/s28/keys/figNNNNN.js. Run from the project root.
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film')
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k2'
os.makedirs(K, exist_ok=True)
Q = json.load(open(f'{T}/lidquads.json'))
SN = json.load(open('snapshots/s28t-tools/sil_new.json'))
def lidpoly(t, pad=4):
    q = Q[f"{min(t, 131.40):.2f}"]
    return [[q[0][0]-pad, q[0][1]-pad], [q[1][0]+pad, q[1][1]-pad], [q[2][0]+pad, q[2][1]+80], [q[3][0]-pad, q[3][1]+80]]
def dilate_ring(ring, r):
    """one ring, or a list of rings (pieces) -> the dilated outline(s): a list of rings when given a list"""
    if not isinstance(ring[0][0], (int, float)):
        return [dilate_ring(rr, r) for rr in ring]
    m = np.zeros((946+400, 2206+400), np.uint8)
    cv2.fillPoly(m, [np.int32(np.array(ring)+200)], 255)
    m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2*r+1,)*2))
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    c = max(cs, key=cv2.contourArea).reshape(-1, 2)-200
    return cv2.approxPolyDP(c.reshape(-1, 1, 2).astype(np.float32), 1.0, True).reshape(-1, 2).tolist()
def write(name, D, nd):
    for key in ('regions', 'ink'):
        for R in D.get(key, []):
            R['r'] = [[[round(x, nd) if nd else int(round(x)), round(y, nd) if nd else int(round(y))] for x, y in ring] for ring in R['r']]
    s = json.dumps(D, separators=(',', ':'))
    open(f'src/shots/s28/keys/{name}.js', 'w').write("// Generated by snapshots/s28t-tools/retrace_fig.py (vector trace of measured outlines and colours; refined silhouette).\nexport default " + s + ";\n")
    print(name, len(s)//1024, 'KB', flush=True)
for t in [float(a) for a in sys.argv[1:]]:
    name = f"fig{int(round(t*100))}"
    area = dilate_ring(SN[f"{t:.2f}"], 2)
    areas = area if not isinstance(area[0][0], (int, float)) else [area]
    spec = {"t": t, "area": areas, "exclude": [lidpoly(t, 5)], "fill_hidden": [], "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
            "ink": [{"lmax": 0.50, "contrast": 0.18, "eps": 0.7, "min_area": 4}, {"lmax": 0.24, "eps": 0.6, "min_area": 3}]}
    sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
    D = json.load(open(out)); D['sil'] = areas; D['lid'] = Q[f"{t:.2f}"]
    write(name, D, 1)
