# s28t: re-trace the orbit room keys: hidden = the refined figure silhouette + 5 px, the lid, and (129.32-129.92) the mug,
# which is now its own layer (mug.js). Same trace settings as retrace_rooms.py. Run from the project root.
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film')
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k2'
os.makedirs(K, exist_ok=True)
Q = json.load(open(f'{T}/lidquads.json'))
SN = json.load(open('snapshots/s28t-tools/sil_new.json'))
MT = json.load(open('snapshots/s28t-tools/mugtrack.json'))
B0 = np.array([1842.0, 741.0])
MUG = [[1775, 592], [1790, 587], [1842, 584], [1895, 587], [1909, 592], [1909, 612], [1928, 630], [1930, 660], [1925, 685],
       [1909, 698], [1909, 730], [1900, 738], [1842, 744], [1785, 738], [1775, 730]]
def mugpoly(t, grow):
    u, v, s = MT[f"{t:.2f}"]; P = (np.array(MUG, float) - B0) * s + [u, v]
    return ring_of(cv2.dilate(ringmask([P.tolist()]), cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * grow + 1,) * 2)))
def lidpoly(t, pad=4):
    q = Q[f"{min(t, 131.40):.2f}"]
    return [[q[0][0]-pad, q[0][1]-pad], [q[1][0]+pad, q[1][1]-pad], [q[2][0]+pad, q[2][1]+80], [q[3][0]-pad, q[3][1]+80]]
def ringmask(rings):
    m = np.zeros((946+400, 2206+400), np.uint8)
    for rr in rings: cv2.fillPoly(m, [np.int32(np.round(np.array(rr)+200))], 255)
    return m
def ring_of(m):
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    c = max(cs, key=cv2.contourArea).reshape(-1, 2)-200
    return cv2.approxPolyDP(c.reshape(-1, 1, 2).astype(np.float32), 1.0, True).reshape(-1, 2).tolist()
def rings_of_all(m):
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    return [cv2.approxPolyDP((c.reshape(-1, 2)-200).reshape(-1, 1, 2).astype(np.float32), 1.0, True).reshape(-1, 2).tolist() for c in cs if cv2.contourArea(c) > 500]
def main():
  for t in [float(a) for a in sys.argv[1:]]:
      name = f"room{int(round(t*100))}"
      sn = SN[f"{t:.2f}"]; sn = sn if not isinstance(sn[0][0], (int, float)) else [sn]
      m2 = cv2.dilate(ringmask(sn), cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (11, 11)))
      hide = rings_of_all(m2) + [lidpoly(t, 6)]
      if t <= 130.0: hide.append(mugpoly(t, 8))
      spec = {"t": t, "area": [[[0, 0], [2206, 0], [2206, 946], [0, 946]]], "exclude": [], "fill_hidden": hide, "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
              "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.9, "min_area": 6}, {"lmax": 0.28, "eps": 0.8, "min_area": 4}]}
      sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
      json.dump(spec, open(sp, 'w'))
      subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
      D = json.load(open(out)); D['hide'] = hide; D['base'] = '#e9dcc0'
      for key in ('regions', 'ink'):
          for R in D.get(key, []):
              R['r'] = [[[int(round(x)), int(round(y))] for x, y in ring] for ring in R['r']]
      s = json.dumps(D, separators=(',', ':'))
      open(f'src/shots/s28/keys/{name}.js', 'w').write("// Generated by snapshots/s28t-tools/retrace_room.py (vector trace of measured outlines and colours; refined figure outline, mug on its own layer).\nexport default " + s + ";\n")
      print(name, len(s)//1024, 'KB', flush=True)

if __name__ == '__main__': main()