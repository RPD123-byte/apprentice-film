# Build all s28 key drawings (vector traces) and write them as JS data modules in src/shots/s28/keys/.
import sys,json,subprocess,os,numpy as np,cv2
os.chdir('/Users/computer/rootline/apprentice-film'); sys.path.insert(0,'snapshots/s28t-tools/t')
T='snapshots/s28t-tools/t'
Q=json.load(open(f'{T}/lidquads.json'))
SO=json.load(open(f'{T}/silh_orbit_out.json'))
H=json.load(open(f'{T}/hero_regions.json'))
hero_sil=max(H['silhouette'],key=len)
def lidpoly(t,pad=4):
    q=Q[f"{min(t,131.40):.2f}"]
    return [[q[0][0]-pad,q[0][1]-pad],[q[1][0]+pad,q[1][1]-pad],[q[2][0]+pad,q[2][1]+80],[q[3][0]-pad,q[3][1]+80]]
def dilate_ring(ring,r):
    m=np.zeros((946+400,2206+400),np.uint8)
    rings=ring if isinstance(ring[0][0],list) else [ring]
    for rr in rings: cv2.fillPoly(m,[np.int32(np.array(rr)+200)],255)
    m=cv2.dilate(m,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(2*r+1,)*2))
    cs,_=cv2.findContours(m,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
    c=max(cs,key=cv2.contourArea).reshape(-1,2)-200
    return cv2.approxPolyDP(c.reshape(-1,1,2).astype(np.float32),1.0,True).reshape(-1,2).tolist()
def run(spec,name):
    sp=f'{T}/k_{name}.json'; out=f'{T}/k_{name}_out.json'
    json.dump(spec,open(sp,'w'))
    if not os.path.exists(out) or os.path.getmtime(out)<os.path.getmtime(sp) or '--force' in sys.argv:
        subprocess.run(['python3',f'{T}/traceview.py',sp,out],check=True)
    return json.load(open(out))
FULL=[[[0,0],[2206,0],[2206,946],[0,946]]]
EXTRA_HIDE={129.32:[[[1222,535],[1308,535],[1308,665],[1222,665]]]}
os.makedirs('src/shots/s28/keys',exist_ok=True)
def roundrings(obj,nd):
    for key in ('regions','ink'):
        for R in obj.get(key,[]):
            R['r']=[[[round(x,nd) if nd else int(round(x)),round(y,nd) if nd else int(round(y))] for x,y in ring] for ring in R['r']]
    return obj
def write(name,obj):
    roundrings(obj,0 if name.startswith('room') else 1)
    s=json.dumps(obj,separators=(',',':'))
    open(f'src/shots/s28/keys/{name}.js','w').write(f"// Generated by snapshots/s28t-tools/t/buildkeys.py (vector trace of measured outlines and colours).\nexport default {s};\n")
    print(name,len(s)//1024,'KB')
which=sys.argv[1] if len(sys.argv)>1 and not sys.argv[1].startswith('--') else 'all'
ONLY=[float(a[5:]) for a in sys.argv if a.startswith('only=')]
# ---- figure keys, orbit
if which in ('all','fig'):
    for t in [129.32,129.52,129.72,129.92,130.12,130.32,130.52,130.72,130.92,131.12]:
        if ONLY and t not in ONLY: continue
        sil=SO[f"{t:.2f}"]
        area=dilate_ring(sil,2)
        D=run({"t":t,"area":[area],"exclude":[lidpoly(t,5)],"fill_hidden":[],"merge":0,"scale":30,"min_size":30,"sp":6,"sr":6,"min_area":10,"ink":[{"lmax":0.50,"contrast":0.18,"eps":0.7,"min_area":4},{"lmax":0.24,"eps":0.6,"min_area":3}]},f"fig{int(round(t*100))}")
        D['sil']=[area]; D['lid']=Q[f"{t:.2f}"]
        write(f"fig{int(round(t*100))}",D)
# ---- figure keys, locked
if which in ('all','lock'):
    SL=json.load(open(f'{T}/silh_locked_out.json'))
    for t in [131.44,132.6,133.12,133.24,133.36,133.88,134.96,135.04,135.12,135.52]:
        if ONLY and t not in ONLY: continue
        # this frame's own silhouette, but never more than 7 px outside the traced hero outline (the figure moves
        # < 6 px while locked; beyond that the colour classes leak into the pink cabinet and the desk)
        m1=np.zeros((946,2206),np.uint8); [cv2.fillPoly(m1,[np.int32(r)],255) for r in SL[f"{t:.2f}"]]
        m1=cv2.dilate(m1,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(5,5)))
        m2=np.zeros((946,2206),np.uint8); cv2.fillPoly(m2,[np.int32(hero_sil)],255)
        m2=cv2.dilate(m2,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(15,15)))
        m3=np.zeros((946,2206),np.uint8); cv2.fillPoly(m3,[np.int32(hero_sil)],255)
        mm=(m1|cv2.dilate(m3,cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(5,5))))&m2
        cs,_=cv2.findContours(mm,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_NONE)
        area=cv2.approxPolyDP(max(cs,key=cv2.contourArea).astype(np.float32),1.0,True).reshape(-1,2).tolist()
        D=run({"t":t,"area":[area],"exclude":[lidpoly(131.36,0)],"fill_hidden":[],"merge":0,"scale":30,"min_size":30,"sp":6,"sr":6,"min_area":10,"ink":[{"lmax":0.50,"contrast":0.18,"eps":0.7,"min_area":4},{"lmax":0.24,"eps":0.6,"min_area":3}]},f"lock{int(round(t*100))}")
        D['sil']=[area]
        write(f"lock{int(round(t*100))}",D)
