# s28t: the bottom strip of the frame (y 836-946: the near desk, papers, cable, laptop base) for 129.32-130.48. The room
# keys re-project it poorly (the near desk has the largest parallax, and what comes into view there lies below the key
# frames' bottom edge), so each source frame gets its own vector trace of the strip (flat/ramped colour regions + two
# ink levels + the faint hatching level), drawn at its own frame under the figure and the lid. -> src/shots/s28/botpatch.js
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film'); sys.path.insert(0, 'snapshots/s28t-tools/t')
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k2'
from grade import pre_frame, hexc
from traceview import rings_of
Y0 = 836
FRAMES = [round(129.32 + 0.04 * i, 2) for i in range(30)]
FRAMES = [t for t in FRAMES if abs(t - 129.56) > 0.001]                 # the source repeats 129.52 at 129.56
def faint(t, area_mask, LMAX=0.78, CON=0.07):
    pre = pre_frame(t).astype(np.float32); H, W = pre.shape[:2]; S = 2
    P2 = cv2.resize(pre, None, fx=S, fy=S, interpolation=cv2.INTER_CUBIC)
    L = cv2.GaussianBlur(0.299 * P2[..., 0] + 0.587 * P2[..., 1] + 0.114 * P2[..., 2], (0, 0), 0.6 * S)
    bg = cv2.dilate(L, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (int(8 * S) + 1,) * 2)); bg = cv2.GaussianBlur(bg, (0, 0), 2.5 * S)
    a2 = cv2.resize(area_mask, (W * S, H * S), interpolation=cv2.INTER_NEAREST)
    strong = cv2.dilate((((L < 0.50) & ((bg - L) > 0.18)) | (L < 0.24)).astype(np.uint8), np.ones((3, 3), np.uint8)) > 0
    m = ((L < LMAX) & ((bg - L) > CON) & ~strong & (a2 > 0)).astype(np.uint8) * 255
    out = []
    for rs in rings_of(m, 0.8, 4, 2, S=S):
        mm = np.zeros((H * S, W * S), np.uint8); cv2.fillPoly(mm, [np.int32(np.array(rs[0]) * S)], 255)
        for h_ in rs[1:]: cv2.fillPoly(mm, [np.int32(np.array(h_) * S)], 0)
        px = P2[(mm > 0) & (m > 0)]
        if len(px): out.append({'c': hexc(np.clip(np.median(px, 0), 0, 1)), 'l': 2, 'r': [[[round(x, 1), round(y, 1)] for x, y in ring] for ring in rs]})
    return out
keys = []
only = [float(a) for a in sys.argv[1:]]
for t in FRAMES:
    if only and t not in only: continue
    area = [[-6, Y0 - 12], [2212, Y0 - 12], [2212, 952], [-6, 952]]
    spec = {"t": t, "area": [area], "exclude": [], "fill_hidden": [], "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
            "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.8, "min_area": 5}, {"lmax": 0.28, "eps": 0.7, "min_area": 4}]}
    name = f"bot{int(round(t*100))}"
    sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True, capture_output=True)
    D = json.load(open(out)); D['y0'] = Y0
    for R in D['regions']: R['r'] = [[[int(round(x)), int(round(y))] for x, y in ring] for ring in R['r']]
    for R in D['ink']: R['r'] = [[[round(x, 1), round(y, 1)] for x, y in ring] for ring in R['r']]
    am = np.zeros((946, 2206), np.uint8); am[Y0 - 12:, :] = 255
    D['ink'] = faint(t, am) + D['ink']
    json.dump(D, open(f'{K}/bot_{name}.json', 'w'), separators=(',', ':'))
    print(name, len(D['regions']), 'regions', len(D['ink']), 'ink', flush=True)
# assemble every traced frame into the module
import glob
allk = sorted([json.load(open(p)) for p in glob.glob(f'{K}/bot_bot*.json')], key=lambda D: D['t'])
if len(allk) != len(FRAMES): sys.exit(f'only {len(allk)} of {len(FRAMES)} frames traced (run without arguments first); botpatch.js not written')
