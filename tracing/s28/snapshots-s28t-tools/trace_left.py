# s28t: the strip at the left edge, 129.32-129.84 (bookshelf, chair, wainscot): no room key sees all of it and the chair
# does not re-project well, so each of those source frames gets its own vector trace of the strip, drawn at its own frame. -> src/shots/s28/leftpatch.js. Run from the project root.
import sys, json, subprocess, os
os.chdir('/Users/computer/rootline/apprentice-film')
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k2'
# the strip x 0..330, y 380..852 (the shelf, books, jar, plant, the chair, the wainscot), traced at each source frame from
# 129.32 to 129.84 (129.56 repeats 129.52 in the source); its right part lies under the hoodie, which is drawn over it
FRAMES = [129.32, 129.36, 129.40, 129.44, 129.48, 129.52, 129.60, 129.64, 129.68, 129.72, 129.76, 129.80, 129.84]
keys = []
for t in FRAMES:
    clip = [[0, 380], [330, 380], [330, 852], [0, 852]]
    area = [[-6, 368], [340, 368], [340, 858], [-6, 858]]
    spec = {"t": t, "area": [area], "exclude": [], "fill_hidden": [], "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
            "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.8, "min_area": 5}, {"lmax": 0.28, "eps": 0.7, "min_area": 4}]}
    name = f"left{int(round(t*100))}"
    sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
    D = json.load(open(out)); D['clip'] = clip
    for key in ('regions', 'ink'):
        for R in D.get(key, []):
            R['r'] = [[[round(x, 1), round(y, 1)] for x, y in ring] for ring in R['r']]
    keys.append(D)
s = ("// Generated by snapshots/s28t-tools/trace_left.py. The strip at the left edge for 129.32-129.84 (bookshelf, chair,\n"
     "// wainscot), which the room keys cannot re-project cleanly: one vector trace per source frame (flat/ramped colour regions\n"
     "// + ink, fitted to the source), each drawn at its own frame inside its clip, feathered at the top; the hoodie is drawn over it.\n"
     "export const LEFTPATCH = " + json.dumps(keys, separators=(',', ':')) + ";\n")
open('src/shots/s28/leftpatch.js', 'w').write(s)
print('leftpatch.js', len(s) // 1024, 'KB')
