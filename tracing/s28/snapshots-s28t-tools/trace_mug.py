# s28t: the mug as its own layer: vector traces of the mug at four source frames (inside its tracked outline + 3 px), and
# the measured track -> src/shots/s28/mug.js. Run from the project root.
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film')
sys.path.insert(0, 'snapshots/s28t-tools')
from retrace_room import mugpoly, MT, B0
T = 'snapshots/s28t-tools/t'; K = 'snapshots/s28t-tools/k2'
KEYT = [129.32, 129.52, 129.72, 129.84]
keys = []
for t in KEYT:
    area = mugpoly(t, 3)
    spec = {"t": t, "area": [area], "exclude": [], "fill_hidden": [], "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
            "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.7, "min_area": 4}, {"lmax": 0.28, "eps": 0.6, "min_area": 3}]}
    sp = f'{K}/k_mug{int(round(t*100))}.json'; out = f'{K}/k_mug{int(round(t*100))}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
    D = json.load(open(out)); D['sil'] = [area]; D['track'] = MT[f"{t:.2f}"]
    for key in ('regions', 'ink'):
        for R in D.get(key, []):
            R['r'] = [[[round(x, 1), round(y, 1)] for x, y in ring] for ring in R['r']]
    keys.append(D)
track = [[float(k)] + [round(v, 2) for v in MT[k]] for k in sorted(MT, key=float)]
s = ("// Generated by snapshots/s28t-tools/trace_mug.py. The mug on the desk as its own layer (129.32-130.12): four vector traces\n"
     "// of the mug (flat/ramped colour regions + ink, fitted to the source), and its measured track per source frame\n"
     "// [t, base u, base v, scale vs 129.32] (template matching on the source, extrapolated as it leaves the frame).\n"
     "export const MUGKEYS = " + json.dumps(keys, separators=(',', ':')) + ";\n"
     "export const MUGTRACK = " + json.dumps(track, separators=(',', ':')) + ";\n")
open('src/shots/s28/mug.js', 'w').write(s)
print('mug.js', len(s) // 1024, 'KB')
