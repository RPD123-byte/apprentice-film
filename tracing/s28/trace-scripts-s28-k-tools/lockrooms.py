# Re-trace the four locked room keys with a tight hidden area: the matching locked figure key's own silhouette + 2 px
# (the camera does not move once locked, so the room right up to the figure outline is real, not filled in).
import sys, json, subprocess, os, numpy as np, cv2
os.chdir('/Users/computer/rootline/apprentice-film')
T = 'snapshots/s28-tools'; K = 'snapshots/s28-k-tools'
Q = json.load(open(f'{T}/lidquads.json'))
def lidpoly(t, pad=4):
    q = Q[f"{min(t, 131.40):.2f}"]
    return [[q[0][0]-pad, q[0][1]-pad], [q[1][0]+pad, q[1][1]-pad], [q[2][0]+pad, q[2][1]+80], [q[3][0]-pad, q[3][1]+80]]
def keysil(name):
    s = open(f'src/shots/s28/keys/{name}.js').read(); return json.loads(s[s.index('{'):].rstrip().rstrip(';'))['sil']
def dilate_rings(rings, r):
    m = np.zeros((946+400, 2206+400), np.uint8)
    for rr in rings: cv2.fillPoly(m, [np.int32(np.array(rr)+200)], 255)
    m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2*r+1,)*2))
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    c = max(cs, key=cv2.contourArea).reshape(-1, 2)-200
    return cv2.approxPolyDP(c.reshape(-1, 1, 2).astype(np.float32), 1.0, True).reshape(-1, 2).tolist()
FULL = [[[0, 0], [2206, 0], [2206, 946], [0, 946]]]
PAIR = {131.6: 'lock13144', 132.8: 'lock13260', 134.2: 'lock13388', 135.6: 'lock13552'}
only = [float(a) for a in sys.argv[1:]]
for t, fk in PAIR.items():
    if only and t not in only: continue
    name = f"room{int(round(t*100))}"
    hide = [dilate_rings(keysil(fk), 2), lidpoly(t, 6)]
    spec = {"t": t, "area": FULL, "exclude": [], "fill_hidden": hide, "merge": 0, "scale": 30, "min_size": 30, "sp": 6, "sr": 6, "min_area": 10,
            "ink": [{"lmax": 0.55, "contrast": 0.14, "eps": 0.9, "min_area": 6}, {"lmax": 0.28, "eps": 0.8, "min_area": 4}]}
    sp = f'{K}/k_{name}.json'; out = f'{K}/k_{name}_out.json'
    json.dump(spec, open(sp, 'w'))
    subprocess.run(['python3', f'{T}/traceview.py', sp, out], check=True)
    D = json.load(open(out)); D['hide'] = hide; D['base'] = '#e9dcc0'
    for key in ('regions', 'ink'):
        for R in D.get(key, []):
            R['r'] = [[[int(round(x)), int(round(y))] for x, y in ring] for ring in R['r']]
    s = json.dumps(D, separators=(',', ':'))
    open(f'src/shots/s28/keys/{name}.js', 'w').write("// Generated by snapshots/s28-k-tools/lockrooms.py (vector trace of measured outlines and colours; tight hidden area).\nexport default " + s + ";\n")
    print(name, len(s)//1024, 'KB', flush=True)
