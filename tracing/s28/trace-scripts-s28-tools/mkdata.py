# Assemble figure data JSON files into src/shots/s28/<name>.js as `export const NAME = {...}` (compact JSON).
import sys,json,cv2,numpy as np
sys.path.insert(0,'snapshots/s28-tools')
from grade import pre_frame,hexc
name=sys.argv[1]; t=float(sys.argv[2]); out=sys.argv[3]; files=sys.argv[4:]
D={}
for fp in files: D.update(json.load(open(fp)))
# colour of each black-shape hole = median pre-grade colour inside it (measured)
if 'black' in D:
    p=pre_frame(t); p8=(p*255).astype(np.uint8)
    for b in D['black']:
        if b['hole']:
            m=np.zeros(p.shape[:2],np.uint8); cv2.fillPoly(m,[np.int32(b['pts'])],255)
            m=cv2.erode(m,np.ones((3,3),np.uint8))
            if m.sum()==0: m=np.zeros(p.shape[:2],np.uint8); cv2.fillPoly(m,[np.int32(b['pts'])],255)
            b['col']=hexc(np.median(p[m>0],0))
s=json.dumps(D,separators=(',',':'))
open(out,'w').write(f"// Generated by snapshots/s28-tools/mkdata.py from measurements of the source at {t} s (shape outlines only).\nexport const {name} = {s};\n")
print(out,len(s))
